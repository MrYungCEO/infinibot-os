#!/usr/bin/env node
// Regenerate src/tool-schemas.ts from a running studio: node scripts/sync-schemas.mjs [http://127.0.0.1:4311]
import { writeFileSync } from "node:fs";
const base = (process.argv[2] ?? "http://127.0.0.1:4311").replace(/\/+$/, "");
const tools = await (await fetch(`${base}/api/tools?schema=1`)).json();
for (const tool of tools) delete tool.inputSchema.$schema;
const body = `// Generated by scripts/sync-schemas.mjs from ${base}/api/tools?schema=1 — do not edit by hand.\nimport type { StudioToolSchema } from "./client.js";\n\nexport const STUDIO_TOOL_SCHEMAS: StudioToolSchema[] = ${JSON.stringify(tools, null, 2)};\n`;
writeFileSync(new URL("../src/tool-schemas.ts", import.meta.url), body);
console.log(`wrote ${tools.length} tool schemas`);
