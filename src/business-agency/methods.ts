/**
 * Business & Agency — the legacy RPC surface the `business-agency` plugin serves.
 *
 * Business HQ, Command, Clients, Sales Pipeline, the Register, Leads & Funnels,
 * Campaigns, Settings › Business and the agency workspace (agency.ops.*) are a
 * first-party plugin (extensions/business-agency). Their backend code still
 * compiles into core, but core no longer registers any of it: the plugin
 * registers every method below as `business-agency.<legacy name>` and wires
 * the legacy name as an alias (manifest `contributes.rpcAliases`), so the
 * control UI, mobile app, satellites and agent tools keep calling the names
 * they know while the plugin is on, and get "unknown method" while it is off.
 *
 * Scopes are the ones these methods had in core (READ_METHODS /
 * WRITE_METHODS in server-methods.ts); methods core never listed stay admin.
 * `business-agency.test.ts` keeps the plugin manifest in step with this table.
 *
 * Stays CORE (not in this table): objrel.* / relations.* (typed edges between
 * every object type), priorities.* (personal daily priorities), branding.*
 * (control-UI branding), business.packs.* (Databases packs), Inbox (gmail.*,
 * email.*) and Research (research.*). See docs/plugins/BUSINESS-AGENCY.md.
 */

