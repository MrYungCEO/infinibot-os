export type BusinessAgencyModule = keyof typeof BUSINESS_AGENCY_LEGACY_METHODS;

export const BUSINESS_AGENCY_PLUGIN_ID = "business-agency";
export const BUSINESS_AGENCY_PLUGIN_NAME = "Business & Agency";

/** Namespaced plugin method for a legacy name: `clients.list` → `business-agency.clients.list`. */
export function businessAgencyPluginMethod(legacy: string): string {
  return `${BUSINESS_AGENCY_PLUGIN_ID}.${legacy}`;
}

export type BusinessAgencyMethod = {
  module: BusinessAgencyModule;
  legacy: string;
  method: string;
  scope: BusinessAgencyScope;
};

/** Flat list of every legacy method with its module, plugin name and scope. */
export function listBusinessAgencyMethods(): BusinessAgencyMethod[] {
  const out: BusinessAgencyMethod[] = [];
  for (const [module, methods] of Object.entries(BUSINESS_AGENCY_LEGACY_METHODS)) {
    for (const [legacy, scope] of Object.entries(methods)) {
      out.push({
        module: module as BusinessAgencyModule,
        legacy,
        method: businessAgencyPluginMethod(legacy),
        scope: scope as BusinessAgencyScope,
      });
    }
  }
  return out;
}

let legacySet: ReadonlySet<string> | null = null;

/** True for a legacy business method name (served only by the plugin). */
export function isBusinessAgencyLegacyMethod(method: string): boolean {
  legacySet ??= new Set(listBusinessAgencyMethods().map((m) => m.legacy));
  return legacySet.has(method);
}
