/**
 * Backend-agnostic coder transcript writer.
 *
 * The activity page reads session transcripts via
 * `readSessionPreviewItemsFromTranscript()` (gateway/session-utils.fs.ts) which
 * scans a JSONL file in one of these locations:
 *
 *   <storeDir>/<sessionId>.jsonl
 *   resolveSessionTranscriptPath(sessionId, agentId)
 *   ~/.infinibot/sessions/<sessionId>.jsonl
 *
 * Each line must be a JSON object with `{ role, content }` where content is
 * either a string or an array of `{ type, text }` parts.
 *
 * Native agents emit transcripts automatically through the agent loop; CLI
 * coder sub-agents (Claude Code / OpenCode / Codex) do NOT — they just write a
 * session-store metadata row and report throttled progress to kanban/registry.
 * As a result the activity page shows the row but no live steps.
 *
 * This module gives the coder tool a fast way to append transcript entries
 * (user prompt on spawn, assistant updates on stdout, final summary) so the
 * run's live progress appears on the /activity page like any other agent —
 * identically for every backend.
 *
 * COORDINATION: opencode-parity — moved here from claude-code/ because nothing
 * in this file is Claude-specific. The old path re-exports from here.
 */

import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";

import { resolveSessionTranscriptCandidates } from "../../gateway/session-utils.fs.js";
import { createSubsystemLogger } from "../../logging/subsystem.js";

const log = createSubsystemLogger("coder-transcript");

export interface CoderTranscriptContext {
  /** sessionId stored on the session-store row (UUID, generated by claude-coder-tool). */
  sessionId: string;
  /** Path to the per-agent session store JSON used by gateway. */
  storePath: string;
  /** Parent agent id (the requester). */
  agentId: string;
}

/**
 * Resolve the transcript file path. Prefers the same dir as storePath so the
 * gateway's preview reader picks it up via the storePath-derived candidate.
 */
function transcriptPathFor(ctx: CoderTranscriptContext): string {
  const candidates = resolveSessionTranscriptCandidates(
    ctx.sessionId,
    ctx.storePath,
    undefined,
    ctx.agentId,
  );
  // First candidate is sessionFile (undefined here), second is <dir>/<sessionId>.jsonl.
  // Pick the storePath-derived one when available so the preview's primary candidate hits.
  if (ctx.storePath) {
    return path.join(path.dirname(ctx.storePath), `${ctx.sessionId}.jsonl`);
  }
  return (
    candidates[0] || path.join(os.homedir(), ".infinibot", "sessions", `${ctx.sessionId}.jsonl`)
  );
}

export interface CoderTranscriptEntry {
  role: "user" | "assistant" | "system" | "tool";
  content: string;
  /** Optional structured parts (overrides content if provided). */
  parts?: Array<{ type: "text" | "output_text" | "input_text"; text: string }>;
  /** Wall-clock timestamp ms. Defaults to Date.now(). */
  ts?: number;
  /** Optional metadata that the preview reader ignores but is useful for debugging. */
  meta?: Record<string, unknown>;
}

const writeQueue = new Map<string, Promise<void>>();

/**
 * Resolve and return the absolute transcript file path for a given context.
 * Exported so the coder tool can persist it on the run record without
 * duplicating the resolution logic.
 */
export function resolveTranscriptPath(ctx: CoderTranscriptContext): string {
  return transcriptPathFor(ctx);
}

/**
 * Wait for all pending transcript writes to settle.
 * Called on graceful/error/timeout/crash exits to ensure no data is lost.
 */
export async function flushTranscriptQueue(): Promise<void> {
  await Promise.allSettled(writeQueue.values());
}

async function appendLine(filePath: string, line: string): Promise<void> {
  const prev = writeQueue.get(filePath) ?? Promise.resolve();
  const next = prev
    .catch(() => undefined)
    .then(async () => {
      await fs.mkdir(path.dirname(filePath), { recursive: true });
      await fs.appendFile(filePath, line, "utf-8");
    });
  writeQueue.set(filePath, next);
  await next;
}

export async function appendCoderTranscriptEntry(
  ctx: CoderTranscriptContext,
  entry: CoderTranscriptEntry,
): Promise<void> {
  try {
    const filePath = transcriptPathFor(ctx);
    const ts = entry.ts ?? Date.now();
    const payload: Record<string, unknown> = {
      role: entry.role,
      ts,
    };
    if (entry.parts && entry.parts.length > 0) {
      payload.content = entry.parts;
    } else {
      payload.content = entry.content;
    }
    if (entry.meta) payload.meta = entry.meta;
    await appendLine(filePath, JSON.stringify(payload) + "\n");
  } catch (err) {
    log.warn("appendCoderTranscriptEntry failed", {
      error: err instanceof Error ? err.message : String(err),
    });
  }
}

/**
 * Convenience wrapper for the common "stream a chunk of stdout into the
 * transcript as an assistant message" pattern. Splits very long chunks so a
 * single appearance doesn't blow the preview reader's per-line cap.
 */
export async function appendCoderStdoutChunk(
  ctx: CoderTranscriptContext,
  chunk: string,
  opts?: { ts?: number; mark?: "stdout" | "stderr" },
): Promise<void> {
  const text = chunk.trim();
  if (!text) return;
  // Cap each appended line at 4 KB; longer chunks get split.
  const MAX = 4096;
  let i = 0;
  while (i < text.length) {
    const slice = text.slice(i, i + MAX);
    await appendCoderTranscriptEntry(ctx, {
      role: "assistant",
      content: slice,
      ts: opts?.ts,
      meta: opts?.mark ? { stream: opts.mark } : undefined,
    });
    i += MAX;
  }
}
