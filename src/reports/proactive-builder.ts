/**
 * ProactiveReportBuilder — builds a branded PDF from structured agent output.
 *
 * Any proactive agent that wants to surface work as a stamped, department-tagged
 * PDF report calls `buildProactiveReport()` instead of hand-rolling puppeteer.
 * The function:
 *   1. Assembles a ReportPayload from the input.
 *   2. Renders the PDF via the canonical black-gold pipeline (renderReport).
 *   3. Saves it under ~/.infinibot/reports/<kind>-<timestamp>.pdf.
 *   4. Upserts a store row with department, tags, sourceAgent, trigger="cron".
 *   5. Optionally fans out to Telegram.
 */

import { mkdirSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { renderReport } from "./render.js";
import { sendDocumentTelegram } from "./sinks/telegram.js";
import { getReportsStore } from "./store.js";
import { categorizeReport } from "./helpers/categorize.js";
import type { ReportPayload, ReportSection } from "./types.js";

// ── Public interface ──────────────────────────────────────────────────────────

export interface ProactiveReportInput {
  /** The report kind id (e.g. "daily_brief"). */
  kind: string;
  /** Human-readable document title. */
  title: string;
  /** One-liner sub-title rendered under the title. */
  subtitle?: string;
  /** Org department — stamped as eyebrow + config field. */
  department: "strategy" | "marketing" | "engineering" | "finance" | "operations";
  /** Agent id that produced this output. */
  agentId: string;
  /** Freeform string tags for the store row. */
  tags?: string[];
  /** Headline metric grid shown in the document header. */
  metrics?: { label: string; value: string | number }[];
  /** Body sections. Each may have a heading, body text, bullets, and/or a table. */
  sections: {
    heading: string;
    body?: string;
    bullets?: string[];
    table?: {
      columns: string[];
      rows: Array<Array<string | number>>;
    };
  }[];
  /**
   * Output sinks. "ui" always saves to disk; "telegram" additionally delivers
   * the PDF via the configured Bot API.  Defaults to ["ui"].
   */
  sinks?: ("ui" | "telegram")[];
  /** Right-aligned footer note (left side is always "InfiniBot Report System"). */
  footer?: string;
}

export interface ProactiveReportResult {
  reportId: string;
  filePath: string;
}

// ── Implementation ────────────────────────────────────────────────────────────

function slugify(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40) || "report";
}

/**
 * Build, render, persist, and optionally deliver a branded proactive report.
 * Returns the persisted row id and the absolute path to the PDF on disk.
 */
export async function buildProactiveReport(
  input: ProactiveReportInput,
): Promise<ProactiveReportResult> {
  const sinks = input.sinks ?? ["ui"];
  const now = Date.now();

  // ── 1. Construct the canonical ReportPayload ────────────────────────────────
  const sections: ReportSection[] = input.sections.map((s) => ({
    heading: s.heading,
    body: s.body,
    bullets: s.bullets,
    table: s.table
      ? { columns: s.table.columns, rows: s.table.rows }
      : undefined,
  }));

  const payload: ReportPayload = {
    title: input.title,
    subtitle: input.subtitle,
    eyebrow: `${input.department.toUpperCase()} REPORT`,
    generatedAt: now,
    metrics: input.metrics,
    sections,
    footer:
      input.footer ??
      `Generated by ${input.agentId} · InfiniBot Agency OS`,
    theme: "black-gold",
  };

  // ── 2. Resolve output path ──────────────────────────────────────────────────
  const stateDir = process.env.INFINIBOT_STATE_DIR ?? join(homedir(), ".infinibot");
  const reportsDir = join(stateDir, "reports");
  mkdirSync(reportsDir, { recursive: true });
  const filename = `${slugify(input.kind)}-${now}.pdf`;
  const filePath = join(reportsDir, filename);

  // ── 3. Render PDF to disk ───────────────────────────────────────────────────
  await renderReport(payload, { savePath: filePath });

  // ── 4. Persist to the reports store ────────────────────────────────────────
  const store = getReportsStore(stateDir);
  const category = categorizeReport({
    kind: input.kind,
    title: input.title,
    sourceAgent: input.agentId,
    explicit: null,
  });
  const rec = store.createReport({
    kind: input.kind,
    title: input.title,
    theme: "black-gold",
    trigger: "cron",
    sourceAgent: input.agentId,
    category,
    config: {
      department: input.department,
      tags: input.tags ?? [],
      sinks,
    },
  });

  // Flip to ready and link the rendered file.
  const { statSync } = await import("node:fs");
  let fileSize = 0;
  try {
    fileSize = statSync(filePath).size;
  } catch {
    /* best-effort */
  }
  store.updateReport(rec.id, {
    status: "ready",
    filePath,
    fileSize,
    renderedAt: now,
    summaryText: input.subtitle ?? null,
  });

  // ── 5. Telegram delivery ────────────────────────────────────────────────────
  if (sinks.includes("telegram")) {
    await sendDocumentTelegram(filePath, {
      caption: input.title,
    }).catch(() => {
      /* non-fatal — delivery failure never aborts the caller */
    });
  }

  return { reportId: rec.id, filePath };
}
