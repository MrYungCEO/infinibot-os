/**
 * Report kind: `content_overview` — marketing content pipeline overview.
 *
 * Filters subagent history for content-producing agents (cmo, scriptwriter,
 * content-director, brand-designer) and produces a marketing-department
 * overview of the content pipeline.
 *
 * Department: marketing | sourceAgent: cmo
 */

import { listSubagentHistory } from "../../agents/subagent-history.js";
import type { CollectedReport, ReportKindModule, Theme } from "../types.js";
import { renderReportHtml } from "../template.js";
import { getTheme } from "../themes/index.js";

export const CONTENT_OVERVIEW_KIND = "content_overview" as const;
const WINDOW_MS = 24 * 60 * 60 * 1000;

/** Agent label substrings that qualify as content-producing agents. */
const CONTENT_AGENT_PATTERNS = [
  "cmo",
  "scriptwriter",
  "content-director",
  "content_director",
  "brand-designer",
  "brand_designer",
  "copywriter",
  "content-writer",
  "content_writer",
];

function isContentAgent(label: string | undefined): boolean {
  if (!label) return false;
  const lower = label.toLowerCase();
  return CONTENT_AGENT_PATTERNS.some((p) => lower.includes(p));
}

function safe<T>(fn: () => T, fallback: T): T {
  try {
    return fn();
  } catch {
    return fallback;
  }
}

export const contentOverviewKind: ReportKindModule = {
  kind: CONTENT_OVERVIEW_KIND,

  async collect({ theme, config }): Promise<CollectedReport> {
    const now = (config?.now as number | undefined) ?? Date.now();
    const windowMs = (config?.windowMs as number | undefined) ?? WINDOW_MS;
    const since = now - windowMs;

    // ── Data gathering ──────────────────────────────────────────────────────
    const { entries } = safe(
      () => listSubagentHistory({ since, limit: 500 }),
      { entries: [] as ReturnType<typeof listSubagentHistory>["entries"], total: 0 },
    );

    const contentEntries = entries.filter((e) => isContentAgent(e.label));
    const piecesProduced = contentEntries.filter((e) => e.status === "complete").length;
    const activeAgents = new Set(
      contentEntries.map((e) => e.label ?? "unnamed"),
    ).size;

    // Produced this period (completed content runs)
    const produced = contentEntries
      .filter((e) => e.status === "complete")
      .sort((a, b) => (b.endedAt ?? 0) - (a.endedAt ?? 0))
      .slice(0, 20)
      .map((e) => {
        const label = e.label ? `[${e.label}] ` : "";
        return `${label}${(e.task ?? "").slice(0, 120)}`;
      });

    // Open opportunities: content runs that errored/timed out
    const openOps = contentEntries
      .filter((e) => e.status !== "complete")
      .sort((a, b) => (b.endedAt ?? 0) - (a.endedAt ?? 0))
      .slice(0, 10)
      .map((e) => {
        const label = e.label ? `[${e.label}] ` : "";
        const reason = e.error ? `: ${e.error.slice(0, 80)}` : ` (${e.status})`;
        return `${label}${(e.task ?? "").slice(0, 100)}${reason}`;
      });

    // ── Build payload and render ────────────────────────────────────────────
    const t = theme ?? getTheme("black-gold");

    const html = renderReportHtml(
      {
        title: "Content Overview",
        subtitle: `Content pipeline status · ${new Date(now).toLocaleDateString()}`,
        eyebrow: "MARKETING REPORT",
        generatedAt: now,
        metrics: [
          { label: "Pieces Produced", value: piecesProduced },
          { label: "Agents Active", value: activeAgents },
        ],
        sections: [
          {
            heading: "Content Pipeline",
            body:
              contentEntries.length > 0
                ? `${contentEntries.length} content agent run${contentEntries.length === 1 ? "" : "s"} ` +
                  `in the last 24 hours across ${activeAgents} agent${activeAgents === 1 ? "" : "s"}. ` +
                  `${piecesProduced} piece${piecesProduced === 1 ? "" : "s"} produced.`
                : "No content agent activity recorded in this window.",
          },
          {
            heading: "Produced This Period",
            count: produced.length,
            bullets: produced.length > 0 ? produced : undefined,
            body: produced.length === 0 ? "No content produced in this window." : undefined,
          },
          {
            heading: "Open Opportunities",
            count: openOps.length,
            bullets: openOps.length > 0 ? openOps : undefined,
            body:
              openOps.length === 0
                ? "No open opportunities or failures to surface."
                : undefined,
          },
        ],
        footer: "Generated by cmo · InfiniBot Agency OS",
        theme: "black-gold",
      },
      t as Theme,
    );

    const summaryText =
      `${piecesProduced} piece${piecesProduced === 1 ? "" : "s"} produced · ` +
      `${activeAgents} agent${activeAgents === 1 ? "" : "s"} active`;

    return {
      title: `Content Overview — ${new Date(now).toLocaleDateString()}`,
      summaryText,
      html,
    };
  },
};

export default contentOverviewKind;
