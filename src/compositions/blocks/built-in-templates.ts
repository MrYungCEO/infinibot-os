/**
 * Built-in composition templates — surfaced in the editor's Templates
 * gallery alongside user-saved ones. Each template is a fully-formed
 * composition seed (canvas + tracks + clips) that the operator can
 * instantiate with one click. The clips reference the motion preset
 * library (`animationPresetId`) so what you see on hover is what you
 * get on stage.
 *
 * Design tenets for this set:
 *   - No media references. Every template renders from text + shape
 *     primitives so it works in a brand-new project with zero assets.
 *   - Style-tag-driven filtering. The editor's Templates panel filters
 *     by `comp.meta.style.tags` matched against `template.tags`, so
 *     authoring a project's style direction (via the /watch slot)
 *     surfaces the right templates first.
 *   - Animation diversity. Across the set we exercise ~10 of the 14
 *     motion presets — Pop In, Kinetic Title, Pulse CTA, Glitch In,
 *     Wipe Left, Bounce In, Soft Fade, Rise & Fade, Shimmer, Spin —
 *     so the gallery doubles as a hands-on tour of what's possible.
 */

import type { CompositionTemplate } from "./types.js";

const now = 0; // sentinel — listTemplates() resolves the actual timestamps

/**
 * Lite helper so each template literal stays compact. The template
 * shape requires `builtIn: true`, `createdAt`, `updatedAt`. Real
 * timestamps are stamped in `listBuiltInTemplates()` at call time.
 */
function tpl(
  partial: Omit<CompositionTemplate, "builtIn" | "createdAt" | "updatedAt">,
): CompositionTemplate {
  return {
    ...partial,
    builtIn: true,
    createdAt: now,
    updatedAt: now,
  };
}

