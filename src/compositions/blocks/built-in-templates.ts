/**
 * Returns the built-in templates with up-to-date `createdAt` /
 * `updatedAt` (timestamped at boot so the gallery's "Newest first"
 * ordering still works — we don't want all 12 to share the same
 * timestamp because then the order is undefined).
 */
export function listBuiltInTemplates(): CompositionTemplate[] {
  const base = Date.now();
  return BUILT_IN_TEMPLATES.map((t, i) => ({
    ...t,
    createdAt: base - (BUILT_IN_TEMPLATES.length - i) * 1000,
    updatedAt: base - (BUILT_IN_TEMPLATES.length - i) * 1000,
  }));
}
