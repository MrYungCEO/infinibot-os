export function readDeliveryPulse(tasksResult, projectNames, now = Date.now()) {
  const tasks = asArray(tasksResult, 'tasks');
  if (tasks.length === 0) return { ...EMPTY_DELIVERY, byStatus: {} };
  const names = projectNames instanceof Map ? projectNames : new Map(Object.entries(projectNames || {}));
  const byStatus = {};
  const endOfDay = new Date(now);
  endOfDay.setHours(23, 59, 59, 999);
  let overdue = 0;
  let dueToday = 0;
  for (const task of tasks) {
    byStatus[task.status] = (byStatus[task.status] ?? 0) + 1;
    if (task.dueAt && task.status !== 'done' && task.status !== 'cancelled') {
      if (task.dueAt < now) overdue += 1;
      else if (task.dueAt <= endOfDay.getTime()) dueToday += 1;
    }
  }
  const rank = { blocked: 0, in_progress: 1, review: 2, ready: 3 };
  const active = tasks
    .filter((task) => task.status in rank)
    .sort(
      (a, b) =>
        rank[a.status] - rank[b.status] ||
        (a.dueAt ?? Number.MAX_SAFE_INTEGER) - (b.dueAt ?? Number.MAX_SAFE_INTEGER),
    )
    .slice(0, 12)
    .map((task) => ({
      id: task.id,
      title: task.title,
      status: task.status,
      priority: task.priority,
      projectName: names.get(task.projectId) ?? 'Unlinked project',
      dueAt: task.dueAt ?? null,
    }));
  return { total: tasks.length, byStatus, active, overdue, dueToday };
}

/** Execution feed → `{ executions, executorEnabled }`, keeping probed non-staged views. */
export function mergeExecutions(executionResult, previous = {}) {
  const views = asArray(executionResult, 'items');
  const executions = {};
  for (const view of views) {
    if (view && view.workItemId) executions[view.workItemId] = view;
  }
  for (const [id, view] of Object.entries(previous || {})) {
    if (!executions[id] && view && view.stage !== AUTONOMY_STAGE) executions[id] = view;
  }
  return {
    executions,
    executorEnabled: unwrap(executionResult, 'executorEnabled', false) === true,
  };
}

