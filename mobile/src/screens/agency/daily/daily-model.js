// ── Generic helpers ────────────────────────────────────────────────────────

export function errorMessage(error) {
  if (!error) return 'unknown error';
  if (typeof error === 'string') return error;
  return error.message ? String(error.message) : String(error);
}

/** `{ key: value }` envelope or the bare value, like the web `unwrap`. */
export function unwrap(value, key, fallback) {
  if (value && typeof value === 'object' && !Array.isArray(value) && key in value) {
    const inner = value[key];
    return inner == null ? fallback : inner;
  }
  return value == null ? fallback : value;
}

export function asArray(value, key) {
  const v = unwrap(value, key, []);
  return Array.isArray(v) ? v : [];
}

/** True when the gateway answered "this method does not exist". */
export function isMissingMethod(error) {
  const msg = errorMessage(error).toLowerCase();
  return /unknown method|method not found|not found: method|unknown rpc|no handler|unsupported method/.test(msg);
}

export function relativeTime(value, now = Date.now()) {
  if (!value) return 'never';
  const delta = now - value;
  const abs = Math.abs(delta);
  const minutes = Math.round(abs / 60_000);
  if (minutes < 1) return delta >= 0 ? 'just now' : 'in under a minute';
  if (minutes < 60) return delta >= 0 ? `${minutes}m ago` : `in ${minutes}m`;
  const hours = Math.round(minutes / 60);
  if (hours < 48) return delta >= 0 ? `${hours}h ago` : `in ${hours}h`;
  const days = Math.round(hours / 24);
  return delta >= 0 ? `${days}d ago` : `in ${days}d`;
}

export function clockTime(value) {
  if (!value) return '—';
  const d = new Date(value);
  const hh = String(d.getHours()).padStart(2, '0');
  const mm = String(d.getMinutes()).padStart(2, '0');
  return `${hh}:${mm}`;
}

export function dueLabel(value, now = Date.now()) {
  if (!value) return 'no due date';
  return value < now ? `overdue ${relativeTime(value, now)}` : `due ${relativeTime(value, now)}`;
}

/** True for a KPI whose numeric content is zero ("0", "$0", "0h"). */
export function isZeroish(value) {
  const digits = String(value ?? '').replace(/[^0-9]/g, '');
  return digits.length > 0 && Number(digits) === 0;
}

export function money(cents, currency = 'USD') {
  const dollars = Math.round((Number(cents) || 0) / 100);
  const sign = dollars < 0 ? '-' : '';
  const body = String(Math.abs(dollars)).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  return currency === 'USD' ? `${sign}$${body}` : `${sign}${body} ${currency}`;
}

export function durationLabel(ms) {
  if (ms === null || ms === undefined || !Number.isFinite(ms)) return null;
  if (ms < 1000) return `${ms}ms`;
  const seconds = Math.round(ms / 1000);
  if (seconds < 60) return `${seconds}s`;
  const minutes = Math.floor(seconds / 60);
  return `${minutes}m ${seconds % 60}s`;
}

export function humanStatus(status) {
  return String(status || '').replace(/_/g, ' ');
}

/** "HH:MM" 24h validation for the time fields (web uses <input type=time>). */
export function isValidClock(value) {
  return /^([01]\d|2[0-3]):[0-5]\d$/.test(String(value || '').trim());
}

/** Lenient "9", "9:5", "0930" → "09:30"; null when unparseable. */
export function normalizeClock(value) {
  const raw = String(value || '').trim();
  if (isValidClock(raw)) return raw;
  let m = raw.match(/^(\d{1,2})(?::(\d{1,2}))?$/);
  if (!m) m = raw.match(/^(\d{2})(\d{2})$/);
  if (!m) return null;
  const h = Number(m[1]);
  const min = Number(m[2] || 0);
  if (h > 23 || min > 59) return null;
  return `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}`;
}

