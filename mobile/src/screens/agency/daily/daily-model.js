export function groupWorkItems(workItems) {
  const byStage = {};
  for (const item of workItems || []) {
    (byStage[item.status] = byStage[item.status] || []).push(item);
  }
  for (const key of Object.keys(byStage)) {
    byStage[key].sort((a, b) => (b.updatedAt ?? 0) - (a.updatedAt ?? 0));
  }
  return byStage;
}

export function openWorkloadByWorker(workItems) {
  const load = new Map();
  for (const item of workItems || []) {
    if (item.status === 'completed' || item.status === 'cancelled') continue;
    load.set(item.workerId, (load.get(item.workerId) ?? 0) + 1);
  }
  return load;
}

