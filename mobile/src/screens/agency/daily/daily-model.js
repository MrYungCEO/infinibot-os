export function sortRecommendations(recommendations, load) {
  return [...(Array.isArray(recommendations) ? recommendations : [])].sort(
    (a, b) =>
      Number(b.eligible) - Number(a.eligible) ||
      b.score - a.score ||
      (load.get(a.workerId) ?? 0) - (load.get(b.workerId) ?? 0),
  );
}

/** Candidate list order + whether the scores discriminate at all. */
export function rankCandidates(employees, recommendations, load) {
  const byScore = new Map((recommendations || []).map((r) => [r.workerId, r]));
  const ordered = [...(employees || [])].sort(
    (a, b) =>
      (byScore.get(b.id)?.score ?? -1) - (byScore.get(a.id)?.score ?? -1) ||
      (load.get(a.id) ?? 0) - (load.get(b.id) ?? 0),
  );
  const distinct = new Set((recommendations || []).map((r) => r.score));
  const discriminating = distinct.size > 1;
  return {
    ordered,
    byScore,
    discriminating,
    flatScore: [...distinct][0] ?? 0,
    topId: discriminating ? ordered[0]?.id ?? null : null,
  };
}

export function candidateWhy(employee, recommendation, showScore) {
  if (!recommendation) return 'not scored by the suitability service';
  if (showScore || !recommendation.eligible) return (recommendation.reasons || []).join('; ');
  return employee.department || 'no department';
}

export function autonomyConsequence(employee) {
  const described = describeAutonomy(employee?.autonomyLevel);
  if (!described) {
    return 'This gateway did not report an autonomy level, so what happens after a run cannot be predicted here.';
  }
  if (described.level === 2 && typeof employee?.approvalThreshold === 'number') {
    return `${employee.name} completes this work unattended while estimated cost stays under ${money(employee.approvalThreshold)}; anything above escalates for approval.`;
  }
  const tail = AUTONOMY_LEVELS.find((e) => e.level === described.level)?.detail ?? described.short;
  return `${employee?.name ?? 'This employee'} — ${tail}`;
}

export function autonomyChipInfo(employee) {
  const described = describeAutonomy(employee?.autonomyLevel);
  if (!described) return { label: 'Autonomy not reported', tone: 'neutral' };
  const bounded = described.level === 2 && typeof employee?.approvalThreshold === 'number';
  return {
    label: `L${described.level} ${described.label}`,
    sub: bounded ? `Auto-completes under ${money(employee.approvalThreshold)}` : described.short,
    tone: described.tone === 'warning' ? 'warning' : described.tone === 'danger' ? 'danger' : described.tone === 'info' ? 'info' : 'neutral',
  };
}

/** The "what will actually happen" note in the handoff sheet. */
export function handoffConsequence({ employee, authorizeNow, executionsLoaded, executorEnabled }) {
  if (!employee) return { tone: 'warning', text: 'Pick an employee to see what autonomy will do.' };
  const backend = employee.modelBinding ?? employee.model ?? 'no backend resolved';
  const conseq = autonomyConsequence(employee);
  if (!executionsLoaded) {
    return {
      tone: 'neutral',
      text: `${conseq} Backend: ${backend}. Whether autonomous execution is switched on could not be read from this gateway — treat "will run" as unknown.`,
    };
  }
  if (!executorEnabled) {
    return {
      tone: 'warning',
      text: `Autonomous execution is OFF. ${authorizeNow ? 'These will be staged and your authorisation recorded, but' : 'These land in Backlog, and even once staged'} nothing will run until cron.agencyOperatingLoop.executeWorkItems is enabled. ${conseq}`,
    };
  }
  if (!authorizeNow) {
    return {
      tone: 'neutral',
      text: `Autonomous execution is ON, but these land in Backlog — the executor only ever picks work up from Staged, so nothing runs until you authorise it on the autonomy board. When you do: ${conseq} Backend: ${backend}.`,
    };
  }
  return {
    tone: 'success',
    text: `These will run. Autonomous execution is on and you are staging them now, so on the next loop tick ${employee.name} spawns ${backend} and starts work. ${conseq}`,
  };
}

export function handoffNotice({ sent, total, failed, workerName, authorizeNow, stageError }) {
  if (failed === 0) {
    const authorised = authorizeNow && !stageError;
    return `${sent} task${sent === 1 ? '' : 's'} handed to ${workerName}${
      authorised
        ? ' and authorised to run'
        : authorizeNow
          ? ` — but staging failed: ${stageError}`
          : ' — queued in Backlog, not yet authorised'
    }.`;
  }
  return `${sent} of ${total} handed to ${workerName}; ${failed} failed. See the failure list above.`;
}

/** Appends a timestamped note to a kanban description (same format as web). */
export function appendNote(description, note, now = Date.now()) {
  const trimmed = String(note || '').trim();
  if (!trimmed) return null;
  const stamp = new Date(now).toISOString().slice(0, 16).replace('T', ' ');
  return `${description ?? ''}\n\n[note ${stamp}] ${trimmed}`.trim();
}

