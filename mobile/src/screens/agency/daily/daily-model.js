export function readLoopStatus(result) {
  const jobs = asArray(result, 'jobs');
  const job = jobs.find((entry) => entry && entry.name === OPERATING_LOOP_JOB_NAME);
  if (!job) return { ...EMPTY_LOOP };
  const st = job.state || {};
  return {
    found: true,
    enabled: job.enabled !== false,
    everyMs: job.schedule?.kind === 'every' ? job.schedule.everyMs ?? null : null,
    nextRunAtMs: st.nextRunAtMs ?? null,
    lastRunAtMs: st.lastRunAtMs ?? null,
    lastStatus: st.lastStatus ?? null,
    lastError: st.lastError ?? null,
    runningAtMs: st.runningAtMs ?? null,
  };
}

export function loopHealth(loop) {
  const cadence = loop.everyMs ? `every ${Math.round(loop.everyMs / 60_000)} min` : 'on a schedule';
  if (!loop.found) return { tone: 'warn', text: 'Scheduled job not found — the loop only runs when triggered here.' };
  if (!loop.enabled) return { tone: 'warn', text: 'Scheduled job is disabled — nothing is being generated automatically.' };
  return { tone: 'ok', text: `Running automatically ${cadence}.` };
}

