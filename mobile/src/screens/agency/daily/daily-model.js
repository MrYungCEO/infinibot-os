export function visibleTasks(tasks, filters) {
  const { search = '', showDone = false, unassignedOnly = true, projectFilter = '' } = filters || {};
  const needle = search.trim().toLowerCase();
  const priorityRank = { urgent: 0, high: 1, normal: 2, low: 3 };
  return (tasks || [])
    .filter((task) => {
      if (!showDone && (task.status === 'done' || task.status === 'cancelled')) return false;
      if (unassignedOnly && task.assigneeId) return false;
      if (projectFilter && task.projectId !== projectFilter) return false;
      if (needle && !String(task.title || '').toLowerCase().includes(needle)) return false;
      return true;
    })
    .sort(
      (a, b) =>
        (priorityRank[a.priority] ?? 9) - (priorityRank[b.priority] ?? 9) ||
        (a.dueAt ?? Number.MAX_SAFE_INTEGER) - (b.dueAt ?? Number.MAX_SAFE_INTEGER) ||
        String(a.title).localeCompare(String(b.title)),
    );
}

