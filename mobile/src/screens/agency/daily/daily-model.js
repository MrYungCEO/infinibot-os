function runStr(run, key) {
  const value = run?.[key];
  return typeof value === 'string' && value.trim() ? value : null;
}
function runNum(run, key) {
  const value = run?.[key];
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}

/** The "WHAT WAS DONE" block of the work-item detail, as plain data. */
export function describeRunResult(item, view) {
  const run = view?.lastRun ?? null;
  const running = item.status === 'in_progress';
  const done = item.status === 'completed';
  if (!run && !running) {
    return { kind: 'none', workerName: view?.workerName ?? 'the assigned employee' };
  }
  const outcome = runStr(run, 'outcome');
  const startedAt = runNum(run, 'startedAt');
  const recordedAt = runNum(run, 'recordedAt');
  const timeline = [];
  if (startedAt) timeline.push({ at: startedAt, label: 'Run started', tone: 'neutral' });
  if (running && !startedAt) timeline.push({ at: null, label: 'Executing now', tone: 'info' });
  if (recordedAt && outcome) {
    timeline.push({
      at: recordedAt,
      label:
        outcome === 'completed'
          ? 'Completed'
          : outcome === 'review'
            ? 'Finished — held for review'
            : outcome === 'escalated'
              ? 'Escalated'
              : `Ended (${outcome})`,
      tone: outcome === 'completed' ? 'success' : outcome === 'escalated' ? 'danger' : 'warning',
    });
  }
  return {
    kind: running ? 'live' : done ? 'done' : 'run',
    title: running ? 'Working on it now' : done ? 'Deliverable — done' : 'Latest run',
    outcome,
    outcomeTone: outcome === 'completed' ? 'success' : outcome === 'escalated' ? 'danger' : 'warning',
    output: runStr(run, 'output'),
    error: runStr(run, 'error'),
    sessionId: runStr(run, 'sessionId'),
    backend: runStr(run, 'backend') ?? view?.backend ?? null,
    duration: durationLabel(runNum(run, 'durationMs')),
    attempts: runNum(run, 'attempts'),
    exitCode: runNum(run, 'exitCode'),
    timeline,
    running,
    done,
  };
}

