#!/usr/bin/env node
/**
 * Post-build step for the mobile WebView embed.
 *
 * Reads dist/agency-world-mobile/index.html, inlines every same-origin
 * <script src> and <link rel="stylesheet" href>, then writes the result both
 * as a standalone HTML and as a JS module (mobile/src/screens/agency-world/
 * world-html.bundled.js) that exports the HTML as a single string the
 * react-native-webview can consume.
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const distDir = path.join(repoRoot, "dist", "agency-world-mobile");
// Vite preserves the input HTML's relative path under outDir, so look in the
// nested src/embed/ folder first and fall back to a flat index.html.
async function findHtml() {
  const candidates = [
    path.join(distDir, "src", "embed", "agency-world-mobile.html"),
    path.join(distDir, "agency-world-mobile.html"),
    path.join(distDir, "index.html"),
  ];
  for (const p of candidates) {
    try { await fs.access(p); return p; } catch { /* try next */ }
  }
  throw new Error(`No embed HTML found under ${distDir}`);
}
const htmlPath = await findHtml();
const outHtmlPath = path.join(distDir, "agency-world-mobile.standalone.html");
const outJsPath = path.join(repoRoot, "mobile", "src", "screens", "agency-world", "world-html.bundled.js");

let html = await fs.readFile(htmlPath, "utf8");

const htmlDir = path.dirname(htmlPath);
async function readSibling(relUrl) {
  // Resolve against the HTML file's directory so "../../foo.js" hops correctly.
  const cleaned = relUrl.split("?")[0].split("#")[0];
  const filePath = path.resolve(htmlDir, cleaned);
  return await fs.readFile(filePath, "utf8");
}

// 1) Inline <link rel="stylesheet" href="…"> → <style>…</style>
const linkRe = /<link\s+([^>]*?)rel=["']stylesheet["']([^>]*?)>/gi;
const linkMatches = [...html.matchAll(linkRe)];
for (const m of linkMatches) {
  const attrs = m[0];
  const hrefMatch = attrs.match(/href=["']([^"']+)["']/i);
  if (!hrefMatch) continue;
  const href = hrefMatch[1];
  // Leave fully-qualified URLs alone (CDN refs etc.).
  if (/^https?:\/\//i.test(href) || /^data:/i.test(href)) continue;
  try {
    const css = await readSibling(href);
    const safeCss = css.replace(/<\/style/gi, "<\\/style");
    html = html.replace(m[0], () => `<style>\n${safeCss}\n</style>`);
  } catch (err) {
    console.warn("[wrap-embed-html] could not inline", href, err.message);
  }
}

// 2) Inline <script type="module" src="…"> and <script src="…">.
const scriptRe = /<script\b([^>]*?)\bsrc=["']([^"']+)["']([^>]*)><\/script>/gi;
const scriptMatches = [...html.matchAll(scriptRe)];
for (const m of scriptMatches) {
  const fullTag = m[0];
  const beforeAttrs = m[1] || "";
  const src = m[2];
  const afterAttrs = m[3] || "";
  if (/^https?:\/\//i.test(src) || /^data:/i.test(src)) continue;
  try {
    const rawJs = await readSibling(src);
    // Vite's modulepreload polyfill stamps the entry's <script src=...> tag
    // as a string literal inside the bundle. Any literal "</script" inside
    // an inline <script> ends the script prematurely, so escape it (the
    // standard HTML-safe pattern is <\/script).
    const js = rawJs.replace(/<\/script/gi, "<\\/script");
    // Use replace() with a function so the inlined JS body is treated as a
    // literal string — String.prototype.replace interprets $&, $1, etc. in
    // a string replacement, and the bundle is full of "$"-laden minified
    // code that would otherwise be mangled.
    const allAttrs = (beforeAttrs + " " + afterAttrs).replace(/\bsrc=["'][^"']+["']/i, "").trim();
    html = html.replace(fullTag, () => `<script ${allAttrs}>\n${js}\n</script>`);
  } catch (err) {
    console.warn("[wrap-embed-html] could not inline", src, err.message);
  }
}

await fs.writeFile(outHtmlPath, html);
console.log("[wrap-embed-html] wrote", path.relative(repoRoot, outHtmlPath), `(${(html.length / 1024).toFixed(1)} KB)`);

// 3) Wrap as a JS module that exports the HTML as a string. Mobile consumes
// this via `import { AGENCY_WORLD_HTML } from './world-html.bundled'`.
const escaped = html.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
const jsModule = `// AUTO-GENERATED by scripts/wrap-embed-html.mjs — do not edit by hand.
// Source: ui/src/embed/agency-world-mobile.{ts,html}
// Rebuild: cd ui && npm run build:embed:mobile
export const AGENCY_WORLD_HTML = \`${escaped}\`;
`;
await fs.mkdir(path.dirname(outJsPath), { recursive: true });
await fs.writeFile(outJsPath, jsModule);
console.log("[wrap-embed-html] wrote", path.relative(repoRoot, outJsPath));
