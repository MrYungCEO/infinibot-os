/**
 * CinematicCamera — drone cam, auto cinematic pans, and recordable shots for the
 * isometric agent world map.
 *
 * This module COMPOSES with the existing CameraDirector (camera-director.ts); it
 * never edits it. It drives the engine through the SAME injected `flyTo` the
 * director uses, and politely tells the director to yield (setUserOverride) while
 * a cinematic move is in flight so the two never fight over the camera.
 *
 * It is engine-agnostic and Lit-free (mirrors camera-director's DI style), so it
 * unit-tests against a mock engine and has no PIXI dependency.
 *
 * Capabilities:
 *  • enterDroneMode() / exitDroneMode() — during quiet periods (no agent activity
 *    for `quietMs`, default 30s) it auto-engages a slow cinematic orbit/dolly
 *    around an "interesting" subject. Exits on user input or new activity.
 *  • cinematicShot(ids, { type }) — composed "establish | close | orbit | reveal"
 *    shots over a target set. Returns a Promise that resolves when the move ends.
 *  • recordCinematic({ durationMs, fps? }) → Promise<Blob> — captures the engine
 *    canvas to a WebM via MediaRecorder + canvas.captureStream.
 *  • Exposes a `window.cinematicCamera` toggle handle.
 *
 * ── Mount one-liner (inside agency-world-viz mountEngine, AFTER the engine +
 *    CameraDirector exist — do NOT edit this file to wire it; wire from the host):
 *
 *    import { CinematicCamera } from "../views/agent-ops/iso/cinematic-camera";
 *    this.cinematic = new CinematicCamera({
 *      now: () => performance.now(),
 *      flyTo: (x, y, s, t) => this.eng()?.cameraFlyTo?.(x, y, s, t),
 *      worldBounds: () => this.eng()?.getWorldBounds?.() ?? null,
 *      agentPositions: () => this.eng()?.getAgentWorldPositions?.() ?? [],
 *      lastActivityAt: () => this.lastWorldEventAt,
 *      recordElement: () => this.eng()?.getCanvas?.() ?? null,
 *      director: this.cameraDirector,
 *    });
 *    this.cinematic.install();        // sets window.cinematicCamera + starts auto-drone
 *    // …and in disconnected/destroy: this.cinematic?.destroy();
 */

import {
  criticallyDampedStep,
  omegaForSettle,
  clamp,
  type SpringState,
} from "./camera-easing";

// ── Public types ────────────────────────────────────────────────────────────

export interface WorldBounds {
  minX: number;
  minY: number;
  maxX: number;
  maxY: number;
}

export interface CinematicTarget {
  id: string;
  x: number;
  y: number;
}

export type CinematicShotType = "establish" | "close" | "orbit" | "reveal";

/** Minimal slice of CameraDirector we coordinate with (so we never import it hard). */
export interface CameraDirectorLike {
  setUserOverride(ms?: number): void;
  setEnabled?(on: boolean): void;
  isEnabled?(): boolean;
}

export interface CinematicCameraDeps {
  /** Monotonic clock (performance.now). */
  now: () => number;
  /** Smoothly fly the engine camera to a world point at a target scale. */
  flyTo: (x: number, y: number, scale: number, timeMs: number) => void;
  /** Current world bounds, or null if unknown (falls back to agent spread). */
  worldBounds: () => WorldBounds | null;
  /** Live agent world positions (for subject picking + framing). */
  agentPositions: () => CinematicTarget[];
  /** performance.now() of the most recent world activity (drives quiet detection). */
  lastActivityAt: () => number;
  /** The canvas (or element) to record. Required only for recordCinematic(). */
  recordElement?: () => HTMLCanvasElement | HTMLElement | null;
  /** Optional CameraDirector to yield while we drive. */
  director?: CameraDirectorLike | null;
  /** Optional reduced-motion gate; defaults to the media query. */
  prefersReducedMotion?: () => boolean;
}

export interface CinematicCameraConfig {
  /** Quiet threshold before auto-drone engages (ms). Default 30000. */
  quietMs: number;
  /** Drone orbit radius as a fraction of the world span. Default 0.22. */
  orbitRadiusFrac: number;
  /** Drone orbit angular speed (rad/sec). Default 0.18. */
  orbitSpeed: number;
  /** Camera scale during drone orbit. Default 1.05. */
  droneScale: number;
  /** Camera scale for an "establish" wide shot. Default 0.55. */
  establishScale: number;
  /** Camera scale for a "close" shot. Default 1.9. */
  closeScale: number;
  /** Camera scale for a "reveal" landing. Default 1.25. */
  revealScale: number;
  /** Re-pick the drone subject every N ms. Default 11000. */
  subjectHoldMs: number;
  /** Auto-engage poll cadence (ms). Default 1500. */
  pollMs: number;
  /** Orbit camera-update cadence (ms) — throttles flyTo spam. Default 90. */
  orbitTickMs: number;
}

export const DEFAULT_CINEMATIC_CONFIG: CinematicCameraConfig = {
  quietMs: 30000,
  orbitRadiusFrac: 0.22,
  orbitSpeed: 0.18,
  droneScale: 1.05,
  establishScale: 0.55,
  closeScale: 1.9,
  revealScale: 1.25,
  subjectHoldMs: 11000,
  pollMs: 1500,
  orbitTickMs: 90,
};

/** Window handle surface (window.cinematicCamera). */
export interface CinematicCameraHandle {
  enterDroneMode(): void;
  exitDroneMode(): void;
  toggleDrone(): void;
  isDroneMode(): boolean;
  /** Pan the main camera to a world point (used by the minimap click hook). */
  panTo(x: number, y: number, scale?: number): void;
  cinematicShot(targetIds: string[], opts?: { type?: CinematicShotType }): Promise<void>;
  recordCinematic(opts: { durationMs: number; fps?: number }): Promise<Blob>;
}

declare global {
  interface Window {
    cinematicCamera?: CinematicCameraHandle;
  }
}

// User-input event kinds that should break the drone out of auto mode.
const USER_INPUT_EVENTS = ["pointerdown", "wheel", "keydown", "touchstart"] as const;
const ORBIT_TICK_CAP_MS = 64;

export class CinematicCamera {
  private readonly deps: CinematicCameraDeps;
  private readonly cfg: CinematicCameraConfig;

  private droneActive = false;
  private autoEnabled = false;
  private recording = false;
  /** While now() < this, auto-drone won't engage — an explicit shot owns the camera. */
  private manualHoldUntil = 0;

  // Auto-engage poll + orbit rAF
  private pollTimer: ReturnType<typeof setInterval> | null = null;
  private rafId: number | null = null;

  // Orbit state
  private orbitAngle = 0;
  private orbitCenter = { x: 0, y: 0 };
  private orbitRadius = 200;
  private subjectId: string | null = null;
  private subjectPickedAt = 0;
  private lastOrbitTickAt = 0;
  private lastFrameAt = 0;

  // Critically-damped springs so the orbit center glides between subjects.
  private springX: SpringState = { x: 0, v: 0 };
  private springY: SpringState = { x: 0, v: 0 };
  private springSeeded = false;

  // Bound listeners (so we can remove them)
  private readonly onUserInput = () => {
    if (this.droneActive) this.exitDroneMode();
    // Briefly suppress re-engage so we don't fight the user right after input.
    this.lastUserInputAt = this.deps.now();
  };
  private lastUserInputAt = 0;

  constructor(deps: CinematicCameraDeps, config?: Partial<CinematicCameraConfig>) {
    this.deps = deps;
    this.cfg = { ...DEFAULT_CINEMATIC_CONFIG, ...config };
  }

  // ── Lifecycle ──────────────────────────────────────────────────────────────

  /** Publish window.cinematicCamera and start the auto-drone poll. */
  install(): void {
    try {
      window.cinematicCamera = {
        enterDroneMode: () => this.enterDroneMode(),
        exitDroneMode: () => this.exitDroneMode(),
        toggleDrone: () => this.toggleDrone(),
        isDroneMode: () => this.isDroneMode(),
        panTo: (x, y, scale) => this.panTo(x, y, scale),
        cinematicShot: (ids, opts) => this.cinematicShot(ids, opts),
        recordCinematic: (opts) => this.recordCinematic(opts),
      };
    } catch { /* window unavailable */ }
    this.startAuto();
  }

  /** Begin auto-engaging drone mode during quiet periods. */
  startAuto(): void {
    if (this.autoEnabled) return;
    this.autoEnabled = true;
    for (const ev of USER_INPUT_EVENTS) {
      window.addEventListener(ev, this.onUserInput, { passive: true });
    }
    this.pollTimer = setInterval(() => this.pollQuiet(), this.cfg.pollMs);
  }

  /** Stop auto-engaging (manual shots/drone still work). */
  stopAuto(): void {
    this.autoEnabled = false;
    if (this.pollTimer) { clearInterval(this.pollTimer); this.pollTimer = null; }
    for (const ev of USER_INPUT_EVENTS) {
      window.removeEventListener(ev, this.onUserInput);
    }
  }

  destroy(): void {
    this.exitDroneMode();
    this.stopAuto();
    try {
      if (window.cinematicCamera) delete window.cinematicCamera;
    } catch { /* ignore */ }
  }

  // ── Quiet detection / auto-engage ────────────────────────────────────────────

  private pollQuiet(): void {
    if (!this.autoEnabled || this.recording) return;
    const now = this.deps.now();
    const quietFor = now - this.deps.lastActivityAt();
    const sinceUserInput = now - this.lastUserInputAt;

    if (this.droneActive) {
      // New activity arrived → step out and let the director resume.
      if (quietFor < this.cfg.quietMs * 0.5) this.exitDroneMode();
      return;
    }

    // An explicit shot / pan owns the camera — don't re-grab it from under the host.
    if (now < this.manualHoldUntil) return;

    // Engage only after sustained quiet AND a grace gap since the last user input.
    if (quietFor >= this.cfg.quietMs && sinceUserInput >= this.cfg.quietMs) {
      this.enterDroneMode();
    }
  }

  // ── Drone mode ────────────────────────────────────────────────────────────────

  isDroneMode(): boolean {
    return this.droneActive;
  }

  toggleDrone(): void {
    this.droneActive ? this.exitDroneMode() : this.enterDroneMode();
  }

  enterDroneMode(): void {
    if (this.droneActive) return;
    this.droneActive = true;
    this.subjectId = null;
    this.subjectPickedAt = 0;
    this.springSeeded = false;
    this.lastFrameAt = this.deps.now();
    this.lastOrbitTickAt = 0;
    this.pickSubject(this.deps.now());

    if (this.reducedMotion()) {
      // Reduced motion: a single gentle establishing hold, no continuous orbit.
      const c = this.orbitCenter;
      this.driveCamera(c.x, c.y, this.cfg.droneScale, 1400);
      return;
    }
    this.startRaf();
  }

  exitDroneMode(): void {
    if (!this.droneActive) return;
    this.droneActive = false;
    this.stopRaf();
    // Hand the camera back to the director cleanly.
    this.deps.director?.setUserOverride?.(0);
  }

  private startRaf(): void {
    if (this.rafId != null) return;
    const loop = () => {
      this.rafId = requestAnimationFrame(loop);
      this.orbitFrame();
    };
    this.rafId = requestAnimationFrame(loop);
  }

  private stopRaf(): void {
    if (this.rafId != null) { cancelAnimationFrame(this.rafId); this.rafId = null; }
  }

  /** One drone frame: glide orbit center toward the subject and dolly around it. */
  private orbitFrame(): void {
    if (!this.droneActive) return;
    const now = this.deps.now();
    const dt = Math.min(ORBIT_TICK_CAP_MS, Math.max(0, now - this.lastFrameAt));
    this.lastFrameAt = now;

    if (now - this.subjectPickedAt > this.cfg.subjectHoldMs) this.pickSubject(now);

    // Glide the orbit center to the (possibly moving) subject.
    const target = this.subjectPos();
    if (!this.springSeeded) {
      this.springX = { x: target.x, v: 0 };
      this.springY = { x: target.y, v: 0 };
      this.springSeeded = true;
    }
    const omega = omegaForSettle(900);
    this.springX = criticallyDampedStep(this.springX, target.x, omega, dt);
    this.springY = criticallyDampedStep(this.springY, target.y, omega, dt);
    this.orbitCenter = { x: this.springX.x, y: this.springY.x };

    this.orbitAngle += this.cfg.orbitSpeed * (dt / 1000);

    // Throttle actual camera dispatch (flyTo) to keep the engine animate plugin sane.
    if (now - this.lastOrbitTickAt < this.cfg.orbitTickMs) return;
    this.lastOrbitTickAt = now;

    // Dolly: gently breathe the radius so it's an orbit + slow push-in/out.
    const breathe = 1 + 0.12 * Math.sin(this.orbitAngle * 0.5);
    const r = this.orbitRadius * breathe;
    const x = this.orbitCenter.x + Math.cos(this.orbitAngle) * r;
    const y = this.orbitCenter.y + Math.sin(this.orbitAngle) * r * 0.6; // iso squash
    const scale = this.cfg.droneScale * (1 + 0.06 * Math.cos(this.orbitAngle * 0.5));
    this.driveCamera(x, y, scale, Math.max(140, this.cfg.orbitTickMs * 2));
  }

  // ── Subject selection ────────────────────────────────────────────────────────

  private pickSubject(now: number): void {
    this.subjectPickedAt = now;
    const agents = this.safeAgents();
    const bounds = this.deps.worldBounds();

    // Compute world span for orbit radius.
    const span = bounds
      ? Math.hypot(bounds.maxX - bounds.minX, bounds.maxY - bounds.minY)
      : agents.length
      ? this.spread(agents)
      : 1600;
    this.orbitRadius = Math.max(120, span * this.cfg.orbitRadiusFrac);

    if (agents.length === 0) {
      // No agents — orbit world center (or origin).
      this.subjectId = null;
      this.orbitCenter = bounds
        ? { x: (bounds.minX + bounds.maxX) / 2, y: (bounds.minY + bounds.maxY) / 2 }
        : { x: 800, y: 600 };
      return;
    }

    // Pick the agent closest to the crowd centroid — the most "interesting" subject.
    const cx = agents.reduce((s, a) => s + a.x, 0) / agents.length;
    const cy = agents.reduce((s, a) => s + a.y, 0) / agents.length;
    let best = agents[0];
    let bestD = Infinity;
    for (const a of agents) {
      const d = Math.hypot(a.x - cx, a.y - cy);
      if (d < bestD) { bestD = d; best = a; }
    }
    // If we already have a valid subject, rotate to a different one for variety.
    if (this.subjectId && agents.length > 1) {
      const others = agents.filter((a) => a.id !== this.subjectId);
      // Deterministic-ish "random" pick driven by the clock (no Math.random in tests).
      best = others[Math.floor(now / 1000) % others.length] ?? best;
    }
    this.subjectId = best.id;
  }

  private subjectPos(): { x: number; y: number } {
    if (this.subjectId) {
      const a = this.safeAgents().find((p) => p.id === this.subjectId);
      if (a) return { x: a.x, y: a.y };
    }
    return this.orbitCenter;
  }

  // ── Composed shots ────────────────────────────────────────────────────────────

  /**
   * Compose a cinematic shot over a set of targets.
   * Resolves when the move's nominal duration elapses.
   */
  cinematicShot(targetIds: string[], opts?: { type?: CinematicShotType }): Promise<void> {
    const type = opts?.type ?? "establish";
    // A deliberate shot takes precedence over auto-drone.
    if (this.droneActive) this.exitDroneMode();

    const agents = this.safeAgents();
    const targets = targetIds
      .map((id) => agents.find((a) => a.id === id))
      .filter((a): a is CinematicTarget => !!a);

    // Fall back to the whole crowd / world center if the targets are unknown.
    const pts: CinematicTarget[] = targets.length ? targets : agents;
    const center = this.centroid(pts);
    const span = pts.length ? this.spread(pts) : 800;

    switch (type) {
      case "close": {
        const c = pts[0] ?? center;
        return this.shotMove(c.x, c.y, this.cfg.closeScale, 1100);
      }
      case "orbit": {
        this.orbitCenter = center;
        this.orbitRadius = Math.max(140, span * 0.5);
        this.subjectId = pts[0]?.id ?? null;
        this.subjectPickedAt = this.deps.now() + 1e9; // hold this subject
        this.orbitAngle = 0;
        this.lastFrameAt = this.deps.now();
        this.lastOrbitTickAt = 0;
        this.springSeeded = false;
        this.droneActive = true;
        if (!this.reducedMotion()) this.startRaf();
        else this.driveCamera(center.x, center.y, this.cfg.droneScale, 1400);
        // Orbit runs until exitDroneMode()/next shot; resolve after one nominal loop.
        const loopMs = Math.max(2000, (2 * Math.PI) / this.cfg.orbitSpeed * 1000);
        return this.wait(loopMs);
      }
      case "reveal": {
        // Start wide + offset, then dolly into the subject.
        const offX = center.x - span * 0.9;
        const offY = center.y - span * 0.6;
        this.holdManual(3400);
        this.driveCamera(offX, offY, this.cfg.establishScale, 700);
        return this.wait(720).then(() =>
          this.shotMove(center.x, center.y, this.cfg.revealScale, 2600),
        );
      }
      case "establish":
      default: {
        // Fit the set: wider span → wider scale.
        const fit = clamp(900 / Math.max(300, span), 0.4, 1.2) * this.cfg.establishScale + 0.2;
        return this.shotMove(center.x, center.y, fit, 2400);
      }
    }
  }

  /** Pan the main camera to a world point (minimap click target). Breaks drone mode. */
  panTo(x: number, y: number, scale = 1.25): void {
    if (this.droneActive) this.exitDroneMode();
    this.holdManual(700);
    this.driveCamera(x, y, scale, 700);
  }

  private shotMove(x: number, y: number, scale: number, timeMs: number): Promise<void> {
    this.holdManual(timeMs);
    this.driveCamera(x, y, scale, timeMs);
    return this.wait(timeMs);
  }

  /** Suppress auto-drone re-engage until a manual move (plus a small grace) finishes. */
  private holdManual(durationMs: number): void {
    this.manualHoldUntil = Math.max(this.manualHoldUntil, this.deps.now() + durationMs + 1500);
  }

  // ── Recording ────────────────────────────────────────────────────────────────

  /**
   * Record the engine canvas to a WebM Blob via MediaRecorder.
   * Requires deps.recordElement to return an HTMLCanvasElement that supports
   * captureStream (all modern Chromium/Firefox builds do).
   */
  recordCinematic(opts: { durationMs: number; fps?: number }): Promise<Blob> {
    const fps = opts.fps ?? 30;
    const durationMs = Math.max(200, opts.durationMs);

    return new Promise<Blob>((resolve, reject) => {
      const el = this.deps.recordElement?.();
      const canvas = el as HTMLCanvasElement | null;
      if (!canvas || typeof (canvas as HTMLCanvasElement).captureStream !== "function") {
        reject(new Error("cinematic: recordElement() did not return a captureStream-capable canvas"));
        return;
      }
      if (typeof MediaRecorder === "undefined") {
        reject(new Error("cinematic: MediaRecorder API unavailable in this environment"));
        return;
      }

      let stream: MediaStream;
      try {
        stream = (canvas as HTMLCanvasElement).captureStream(fps);
      } catch (e) {
        reject(new Error(`cinematic: captureStream failed: ${(e as Error).message}`));
        return;
      }

      const mime = this.pickMimeType();
      let recorder: MediaRecorder;
      try {
        recorder = new MediaRecorder(stream, mime ? { mimeType: mime } : undefined);
      } catch (e) {
        reject(new Error(`cinematic: MediaRecorder init failed: ${(e as Error).message}`));
        return;
      }

      const chunks: BlobPart[] = [];
      this.recording = true;
      recorder.ondataavailable = (ev: BlobEvent) => {
        if (ev.data && ev.data.size > 0) chunks.push(ev.data);
      };
      recorder.onerror = (ev: Event) => {
        this.recording = false;
        reject(new Error(`cinematic: MediaRecorder error: ${String((ev as unknown))}`));
      };
      recorder.onstop = () => {
        this.recording = false;
        for (const t of stream.getTracks()) t.stop();
        resolve(new Blob(chunks, { type: mime || "video/webm" }));
      };

      recorder.start();
      setTimeout(() => {
        if (recorder.state !== "inactive") recorder.stop();
      }, durationMs);
    });
  }

  private pickMimeType(): string | null {
    if (typeof MediaRecorder === "undefined" || !MediaRecorder.isTypeSupported) return null;
    const candidates = [
      "video/webm;codecs=vp9",
      "video/webm;codecs=vp8",
      "video/webm",
    ];
    for (const c of candidates) {
      if (MediaRecorder.isTypeSupported(c)) return c;
    }
    return null;
  }

  // ── Helpers ────────────────────────────────────────────────────────────────────

  /** Drive the engine camera, asking the director to yield for the move's duration. */
  private driveCamera(x: number, y: number, scale: number, timeMs: number): void {
    this.deps.director?.setUserOverride?.(timeMs + 300);
    try {
      this.deps.flyTo(x, y, scale, timeMs);
    } catch { /* engine gone */ }
  }

  private safeAgents(): CinematicTarget[] {
    try {
      const a = this.deps.agentPositions();
      return Array.isArray(a) ? a.filter((p) => p && Number.isFinite(p.x) && Number.isFinite(p.y)) : [];
    } catch {
      return [];
    }
  }

  private centroid(pts: CinematicTarget[]): { x: number; y: number } {
    if (!pts.length) {
      const b = this.deps.worldBounds();
      return b ? { x: (b.minX + b.maxX) / 2, y: (b.minY + b.maxY) / 2 } : { x: 800, y: 600 };
    }
    const x = pts.reduce((s, p) => s + p.x, 0) / pts.length;
    const y = pts.reduce((s, p) => s + p.y, 0) / pts.length;
    return { x, y };
  }

  private spread(pts: CinematicTarget[]): number {
    if (pts.length < 2) return 600;
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const p of pts) {
      minX = Math.min(minX, p.x); maxX = Math.max(maxX, p.x);
      minY = Math.min(minY, p.y); maxY = Math.max(maxY, p.y);
    }
    return Math.hypot(maxX - minX, maxY - minY);
  }

  private reducedMotion(): boolean {
    if (this.deps.prefersReducedMotion) {
      try { return !!this.deps.prefersReducedMotion(); } catch { /* fall through */ }
    }
    try {
      return !!window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
    } catch {
      return false;
    }
  }

  private wait(ms: number): Promise<void> {
    return new Promise((res) => setTimeout(res, ms));
  }
}
