export function drawPixelText(g: PIXI.Graphics, text: string, x: number, y: number, color: number, scale = 1): number {
  let cursorX = x;
  const chars = text.toUpperCase().split('');
  for (const char of chars) {
    const pattern = PIXEL_FONT[char];
    if (!pattern) { cursorX += 4 * scale; continue; }
    for (let row = 0; row < pattern.length; row++) {
      for (let col = 0; col < pattern[row].length; col++) {
        if (pattern[row][col]) {
          g.beginFill(color);
          g.drawRect(cursorX + col * scale, y + row * scale, scale, scale);
          g.endFill();
        }
      }
    }
    cursorX += (pattern[0].length + 1) * scale;
  }
  return cursorX - x;
}

export function measurePixelText(text: string, scale = 1): number {
  let width = 0;
  const chars = text.toUpperCase().split('');
  for (const char of chars) {
    const pattern = PIXEL_FONT[char];
    if (!pattern) { width += 4 * scale; continue; }
    width += (pattern[0].length + 1) * scale;
  }
  return width - scale;
}
