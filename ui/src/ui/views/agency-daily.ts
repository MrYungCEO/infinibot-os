/**
 * True when the only thing standing between this card and execution is that it
 * has not been staged yet. The gateway reports that as a `blockedReason`, but
 * repeating "move the card to accepted" on a backlog card — or worse, inside
 * the dialog whose confirm button does exactly that — is noise. Everything else
 * it reports is a real blocker and stays loud.
 */
function isUnstagedOnly(view: WorkItemExecutionView | undefined): boolean {
  return !!view && !view.executionEligible && view.terminalStage !== null;
}

/** One-line answer to "what happens if this runs?", straight from the gateway. */
function outcomeLabel(view: WorkItemExecutionView | undefined): string | null {
  if (!view) return null;
  if (view.blockedReason && !isUnstagedOnly(view)) return null;
  if (view.terminalStage === "completed") return "runs to completion automatically";
  if (view.terminalStage === "review") return "runs, then stops in Review for you";
  return null;
}

function backendLabel(view: WorkItemExecutionView | undefined, fallback?: string): string {
  return view?.backend ?? fallback ?? "no backend resolved";
}

/**
 * Opens the full-expansion detail modal and, in the same gesture, fetches the
 * card's real execution record (readiness + `lastRun`: the final deliverable,
 * the session id, duration and outcome). The board summary only carries that
 * for staged cards, so without this a completed card in the Completed column
 * would open a modal that could not show WHAT WAS DONE.
 */
function openWorkItemFull(
  host: AgencyDailyHost,
  client: GatewayBrowserClient,
  workItemId: string,
): void {
  openWorkItemDetail(host as unknown as AgencyAutonomyHost, workItemId);
  void loadWorkItemExecutionDetail(host, client, workItemId);
}

function renderCard(
  host: AgencyDailyHost,
  state: AgencyDailyState,
  client: GatewayBrowserClient,
  item: EmployeeWorkItem,
  employeeName: string,
  employeeModel: string | undefined,
): TemplateResult {
  const view = state.executions[item.id];
  const busy = state.busyWorkItemId === item.id;
  const targets = WORK_ITEM_TRANSITIONS[item.status] ?? [];
  const outcome = outcomeLabel(view);
  const staged = item.status === AUTONOMY_STAGE;
  const canStage = targets.includes(AUTONOMY_STAGE);
  const lastRunOutcome =
    typeof view?.lastRun?.outcome === "string" ? (view.lastRun.outcome as string) : null;
  return html`
    <article
      class="agx-card st-${item.status} p-${item.priority} ${busy ? "is-busy" : ""} ${state.draggingWorkItemId ===
      item.id
        ? "is-dragging"
        : ""}"
      tabindex="0"
      role="button"
      draggable=${busy ? "false" : "true"}
      aria-label="${item.title}. Stage: ${STAGE_LABELS[item.status]}. Assigned to ${employeeName}.${outcome
        ? ` If run, it ${outcome}.`
        : ""}${view?.blockedReason ? ` Blocked: ${view.blockedReason}.` : ""} Open for full details."
      @click=${(event: MouseEvent) => {
        if ((event.target as HTMLElement).closest("input,button,a,select,label")) return;
        openWorkItemFull(host, client, item.id);
      }}
      @keydown=${(event: KeyboardEvent) => {
        if (event.key !== "Enter" && event.key !== " ") return;
        if ((event.target as HTMLElement).closest("input,button,a,select,label")) return;
        event.preventDefault();
        openWorkItemFull(host, client, item.id);
      }}
      @dragstart=${(event: DragEvent) => {
        event.dataTransfer?.setData("text/plain", item.id);
        if (event.dataTransfer) event.dataTransfer.effectAllowed = "move";
        beginWorkItemDrag(host, item.id);
      }}
      @dragend=${() => endWorkItemDrag(host)}
    >
      <span class="agx-card-title">
        ${item.status === "in_progress"
          ? html`<span class="agx-live-dot" aria-hidden="true"></span>`
          : item.status === "completed"
            ? html`<span class="agx-done-tick" aria-hidden="true">✓</span>`
            : nothing}${item.title}</span
      >
      ${item.status === "in_progress"
        ? html`<span class="agx-run-shimmer" role="status" aria-label="Agent is executing this now"
            ><span></span></span
          >`
        : nothing}
      <div class="agx-chips">
        <span class="agx-chip ${item.status === "in_progress" ? "run" : item.status === "completed" ? "ok" : item.status === "escalated" ? "crit" : item.status === AUTONOMY_STAGE ? "gold" : ""}"
          >${item.status === "in_progress"
            ? "running"
            : item.status === AUTONOMY_STAGE
              ? "staged"
              : STAGE_LABELS[item.status].toLowerCase()}</span
        >
        <span class="agx-chip ${item.priority === "urgent" ? "crit" : item.priority === "high" ? "warn" : ""}"
          >${item.priority}</span
        >
        <span class="agx-chip gold">${employeeName}</span>
        <span class="agx-chip">${backendLabel(view, employeeModel)}</span>
        ${view ? html`<span class="agx-chip">autonomy L${view.autonomyLevel}</span>` : nothing}
        ${outcome
          ? html`<span class="agx-chip ${view?.terminalStage === "completed" ? "ok" : "info"}"
              >→ ${view?.terminalStage}</span
            >`
          : nothing}
        ${item.escalationLevel
          ? html`<span class="agx-chip crit">escalation L${item.escalationLevel}</span>`
          : nothing}
      </div>
      <span class="agx-card-meta"
        >${dueLabel(item.dueAt)}${item.waitingReason ? ` · ${item.waitingReason}` : ""}${lastRunOutcome
          ? ` · last run ${lastRunOutcome}`
          : ""}</span
      >
      ${outcome
        ? html`<span class="agx-card-meta"
            >${staged ? "Authorised — " : "If staged: "}${outcome}.</span
          >`
        : nothing}
      ${view?.blockedReason && !isUnstagedOnly(view)
        ? html`<span class="agx-card-blocked" role="note"
            >Will not run: ${view.blockedReason}</span
          >`
        : nothing}
      ${canStage
        ? html`<button
            type="button"
            class="agx-btn tiny authorize"
            ?disabled=${busy}
            aria-label="Stage ${item.title} for autonomous work — opens an authorisation review"
            @click=${() => void openStagePrompt(host, client, item.id)}
          >
            Stage for autonomous work…
          </button>`
        : nothing}
      ${targets.length
        ? html`<div class="agx-card-actions">
            <label class="agx-sr" for="stage-${item.id}">Move ${item.title} to stage</label>
            <select
              id="stage-${item.id}"
              class="agx-select"
              .value=${""}
              ?disabled=${busy}
              aria-label="Move ${item.title} to another stage"
              @change=${(event: Event) => {
                const select = event.target as HTMLSelectElement;
                const next = select.value as WorkItemStatus | "";
                select.value = "";
                if (next) requestWorkItemStage(host, client, item.id, next);
              }}
            >
              <option value="">Move to…</option>
              ${targets.map(
                (target) => html`<option value=${target}>
                  ${STAGE_LABELS[target]}${target === AUTONOMY_STAGE ? " ⚠" : ""}
                </option>`,
              )}
            </select>
          </div>`
        : nothing}
    </article>
  `;
}

export function renderBoard(
  host: AgencyDailyHost,
  state: AgencyDailyState,
  client: GatewayBrowserClient,
): TemplateResult {
  const names = new Map(state.employees.map((employee) => [employee.id, employee.name] as const));
  const models = new Map(state.employees.map((employee) => [employee.id, employee.model] as const));
  const byStage = new Map<WorkItemStatus, EmployeeWorkItem[]>();
  for (const item of state.workItems) {
    const bucket = byStage.get(item.status);
    if (bucket) bucket.push(item);
    else byStage.set(item.status, [item]);
  }
  const stagedCount = byStage.get(AUTONOMY_STAGE)?.length ?? 0;
  const total = state.workItems.length;
  // The delivery board hands tasks over by dropping them onto this board. Both
  // controllers hang off the same host object, so the cast is a view of the
  // same app state rather than a second one.
  const autonomyHost = host as unknown as AgencyAutonomyHost;

  return html`
    <section class="agx-panel agx-board-panel">
      <header class="agx-panel-head">
        <span>Live work board</span>
        <span class="agx-count"
          >${total} item${total === 1 ? "" : "s"} · ${stagedCount} staged${state.liveAt
            ? ` · live ${relativeTime(state.liveAt)}`
            : ""}</span
        >
        <button
          type="button"
          class="agx-btn tiny agx-panel-act"
          ?disabled=${state.employees.length === 0}
          aria-label="Assign a new work item to an employee"
          title=${state.employees.length === 0
            ? "Hire a worker before assigning work"
            : "Assign a one-off work item"}
          @click=${() => openDailyComposer(host, "work-item")}
        >
          + Assign work
        </button>
      </header>
      ${state.executorEnabled
        ? html`<div class="agx-board-note" role="status">
            <strong>Autonomous execution is ON.</strong>
            Moving a card into <strong>Staged</strong> authorises the assigned AI employee to
            spawn its coder backend and do the work. Nothing in Backlog ever runs.
          </div>`
        : html`<div class="agx-board-note warn" role="status">
            <strong>Autonomous execution is OFF.</strong>
            Staging a card still records your authorisation, but
            <strong>nothing will run</strong> until
            <code>cron.agencyOperatingLoop.executeWorkItems</code> is enabled. Cards will sit in
            Staged.
          </div>`}
      <div class="agx-board ${total === 0 ? "is-empty" : ""}">
        ${BOARD_COLUMNS.map((column) => {
          const items = (byStage.get(column.key) ?? []).sort(
            (a, b) => (b.updatedAt ?? 0) - (a.updatedAt ?? 0),
          );
          const shown = items.slice(0, COLUMN_CARD_CAP);
          const dragged = state.draggingWorkItemId
            ? state.workItems.find((entry) => entry.id === state.draggingWorkItemId)
            : undefined;
          const droppable = dragged
            ? (WORK_ITEM_TRANSITIONS[dragged.status] ?? []).includes(column.key)
            : false;
          // A delivery task is not a work item yet, so it can only land in the
          // two columns a brand-new work item can legally occupy: Backlog, or
          // Staged when the operator authorises it in the same gesture.
          const acceptsDelivery = column.key === "queued" || column.key === AUTONOMY_STAGE;
          return html`
            <div
              class="agx-col ${column.gate ? "is-gate" : ""} ${(droppable || acceptsDelivery) &&
              state.dragOverStage === column.key
                ? "is-dropzone"
                : ""}"
              role="group"
              aria-label="${column.label} — ${items.length} item${items.length === 1 ? "" : "s"}. ${column.hint}"
              @dragover=${(event: DragEvent) => {
                const delivery = event.dataTransfer?.types.includes(DELIVERY_DRAG_TYPE) ?? false;
                if (delivery) {
                  if (!acceptsDelivery) return;
                  event.preventDefault();
                  if (event.dataTransfer) event.dataTransfer.dropEffect = "copy";
                  setDragOverStage(host, column.key);
                  setDragOverAutonomy(autonomyHost, true);
                  return;
                }
                if (!droppable) return;
                event.preventDefault();
                if (event.dataTransfer) event.dataTransfer.dropEffect = "move";
                setDragOverStage(host, column.key);
              }}
              @dragleave=${() => {
                if (state.dragOverStage === column.key) setDragOverStage(host, null);
                setDragOverAutonomy(autonomyHost, false);
              }}
              @drop=${(event: DragEvent) => {
                event.preventDefault();
                if (event.dataTransfer?.types.includes(DELIVERY_DRAG_TYPE)) {
                  if (!acceptsDelivery) return;
                  const ids = (event.dataTransfer.getData(DELIVERY_DRAG_TYPE) || "")
                    .split(",")
                    .filter(Boolean);
                  setDragOverStage(host, null);
                  setDragOverAutonomy(autonomyHost, false);
                  if (ids.length) {
                    openHandoff(autonomyHost, client, ids, {
                      authorizeNow: column.key === AUTONOMY_STAGE,
                    });
                  }
                  return;
                }
                const id = event.dataTransfer?.getData("text/plain") || state.draggingWorkItemId;
                endWorkItemDrag(host);
                if (id) requestWorkItemStage(host, client, id, column.key);
              }}
            >
              <div class="agx-col-head">
                <span>${column.label}</span>
                <span class="agx-col-n">${items.length}</span>
              </div>
              <div class="agx-col-hint">${column.hint}</div>
              <div class="agx-col-body">
                ${shown.length === 0
                  ? html`<div class="agx-col-empty">empty</div>`
                  : shown.map((item) =>
                      renderCard(
                        host,
                        state,
                        client,
                        item,
                        names.get(item.workerId) ?? item.workerId,
                        models.get(item.workerId) ?? undefined,
                      ),
                    )}
                ${items.length > shown.length
                  ? html`<div class="agx-col-empty">
                      +${items.length - shown.length} more not shown
                    </div>`
                  : nothing}
              </div>
            </div>
          `;
        })}
      </div>
      ${total === 0
        ? html`<div style="padding:0 11px 11px">
            ${renderEmpty({
              inline: true,
              glyph: "◇",
              title: "The board is waiting for its first card",
              body: "The loop turns recurring responsibilities into Backlog cards. Add one, or assign a one-off item — either way nothing runs until you stage it.",
              actions: [
                composerAction(host, "responsibility", "Add a responsibility"),
                composerAction(host, "work-item", "Assign a one-off item", {}, false),
              ],
            })}
          </div>`
        : nothing}
    </section>
  `;
}

/**
 * The authorisation prompt. Every route into the staged column lands here —
 * button, keyboard stage select and drag alike — because staging is the moment
 * a human authorises an AI employee to go and do the work.
 */
function renderStagePrompt(
  host: AgencyDailyHost,
  state: AgencyDailyState,
  client: GatewayBrowserClient,
): TemplateResult | typeof nothing {
  const prompt = state.stagePrompt;
  if (!prompt) return nothing;
  const view = prompt.view;
  const outcome = outcomeLabel(view ?? undefined);
  return html`
    <div
      class="agx-modal-scrim"
      @click=${(event: Event) => {
        if (event.target === event.currentTarget) closeStagePrompt(host);
      }}
      @keydown=${(event: KeyboardEvent) => {
        if (event.key === "Escape") closeStagePrompt(host);
      }}
    >
      <div
        class="agx-modal"
        role="dialog"
        aria-modal="true"
        aria-label="Authorise autonomous work on ${prompt.title}"
      >
        <h2>Authorise autonomous work</h2>
        <div class="agx-modal-body">
          <div>
            Staging <strong>${prompt.title}</strong> moves it out of the backlog and makes it
            eligible for an AI employee to execute without further approval.
          </div>
          ${prompt.loading
            ? html`<div class="agx-note">Checking execution readiness…</div>`
            : nothing}
          ${prompt.error ? html`<div class="agx-note warn">${prompt.error}</div>` : nothing}
          ${view
            ? html`<dl>
                <dt>Employee</dt>
                <dd>${view.workerName}</dd>
                <dt>Backend</dt>
                <dd>${view.backend ?? "none resolved"}</dd>
                <dt>Autonomy</dt>
                <dd>level ${view.autonomyLevel}</dd>
                <dt>On success</dt>
                <dd>
                  ${view.terminalStage === "completed"
                    ? "completes automatically — no further human step"
                    : view.terminalStage === "review"
                      ? "stops in Review for you to sign off"
                      : "would not run"}
                </dd>
              </dl>`
            : nothing}
          ${!state.executorEnabled
            ? html`<div class="agx-note warn">
                Autonomous execution is switched off
                (<code>cron.agencyOperatingLoop.executeWorkItems</code>). Your authorisation is
                recorded and the card moves to Staged, but nothing will run until it is enabled.
              </div>`
            : view?.blockedReason && !isUnstagedOnly(view)
              ? html`<div class="agx-note warn">This card will not run: ${view.blockedReason}</div>`
              : outcome
                ? html`<div class="agx-note ok">
                    On the next loop tick, ${view?.workerName} ${outcome} using
                    ${view?.backend ?? "its backend"}.
                  </div>`
                : nothing}
        </div>
        <div class="agx-modal-foot">
          <button
            type="button"
            class="agx-btn ghost"
            aria-label="Cancel — do not stage this work item"
            @click=${() => closeStagePrompt(host)}
          >
            Cancel
          </button>
          <button
            type="button"
            class="agx-btn authorize"
            style="width:auto"
            ?disabled=${prompt.submitting}
            aria-label="Authorise and stage ${prompt.title} for autonomous work"
            @click=${() => void confirmStagePrompt(host, client)}
          >
            ${prompt.submitting ? "Staging…" : "Authorise & stage"}
          </button>
        </div>
      </div>
    </div>
  `;
}

