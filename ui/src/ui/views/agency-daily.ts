function riskTone(risk: string): string {
  return risk === "high" ? "crit" : risk === "medium" ? "warn" : "";
}

/**
 * True for a KPI whose numeric content is zero ("0", "$0", "0h").
 *
 * Dashboards read badly when every tile shouts in gold regardless of whether it
 * says anything; dimming the zeros lets the one number that matters land.
 */
function isZeroish(value: string): boolean {
  const digits = value.replace(/[^0-9]/g, "");
  return digits.length > 0 && Number(digits) === 0;
}

function dueLabel(value: number | null): string {
  if (!value) return "no due date";
  return value < Date.now() ? `overdue ${relativeTime(value)}` : `due ${relativeTime(value)}`;
}

interface EmptyAction {
  label: string;
  primary?: boolean;
  run: () => void;
}

/**
 * The empty state, composed rather than apologetic.
 *
 * A young agency has no work items, so on this page the empty state is the
 * common case, not the exception — five of the six panels render one. Each is
 * therefore given a glyph, a headline, one sentence of "why this is empty" and
 * the button that fills it, so the page reads as a product waiting for input
 * instead of a product that failed to load.
 */
function renderEmpty(opts: {
  glyph: string;
  title: string;
  body: string;
  actions?: EmptyAction[];
  inline?: boolean;
}): TemplateResult {
  const actions = (opts.actions ?? []).filter(Boolean);
  const copy = html`
    <div class="agx-empty-copy">
      <strong>${opts.title}</strong>
      <span>${opts.body}</span>
    </div>
  `;
  return html`
    <div class="agx-empty ${opts.inline ? "inline" : ""}">
      <span class="agx-empty-glyph" aria-hidden="true">${opts.glyph}</span>
      ${copy}
      ${actions.length
        ? html`<div class="agx-empty-actions">
            ${actions.map(
              (action) => html`<button
                type="button"
                class="agx-btn ${action.primary ? "primary" : ""}"
                @click=${action.run}
              >
                ${action.label}
              </button>`,
            )}
          </div>`
        : nothing}
    </div>
  `;
}

/** Opens Agency Operations, for the few things this surface cannot do itself. */
function openOps(host: AgencyDailyHost): EmptyAction | null {
  if (!host.setTab) return null;
  return { label: "Open Agency Operations", run: () => host.setTab?.("agency-operations") };
}

function composerAction(
  host: AgencyDailyHost,
  kind: DailyComposerKind,
  label: string,
  patch: Partial<DailyComposer> = {},
  primary = true,
): EmptyAction {
  return { label, primary, run: () => openDailyComposer(host, kind, patch) };
}

function renderLoopBanner(
  host: AgencyDailyHost,
  state: AgencyDailyState,
  client: GatewayBrowserClient,
): TemplateResult {
  const loop = state.loop;
  const cadence = loop.everyMs ? `every ${Math.round(loop.everyMs / 60_000)} min` : "on a schedule";
  const health = !loop.found
    ? { tone: "warn", text: "Scheduled job not found — the loop only runs when triggered here." }
    : !loop.enabled
      ? { tone: "warn", text: "Scheduled job is disabled — nothing is being generated automatically." }
      : { tone: "ok", text: `Running automatically ${cadence}.` };
  return html`
    <div class="agx-toolbar" role="status">
      <span class="agx-tag ${health.tone}">Operating loop</span>
      <span class="agx-scope-note">
        ${health.text}
        Last run <strong>${relativeTime(loop.lastRunAtMs)}</strong>${loop.lastStatus
          ? html` (${loop.lastStatus})`
          : nothing}
        · next ${loop.nextRunAtMs ? clockTime(loop.nextRunAtMs) : "—"}
        ${loop.runningAtMs ? html` · <strong>running now</strong>` : nothing}
      </span>
      ${loop.lastError
        ? html`<span class="agx-tag crit" title=${loop.lastError}>last run errored</span>`
        : nothing}
      <span style="margin-left:auto;display:flex;gap:8px;align-items:center">
        ${state.loopResult ? html`<span class="agx-scope-note">${state.loopResult}</span>` : nothing}
        <button
          type="button"
          class="agx-btn"
          ?disabled=${state.loopRunning}
          aria-label="Run the workforce operating loop now"
          @click=${() => void runOperatingLoopNow(host, client)}
        >
          ${state.loopRunning ? "Running…" : "Run now"}
        </button>
      </span>
    </div>
  `;
}

