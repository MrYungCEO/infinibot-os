/**
 * <world-minimap> — corner radar / HUD for the isometric agent world map.
 *
 * A self-contained, Lit-free custom element. It renders a top-down schematic of
 * the world onto a small canvas fixed bottom-right (~180×120), glassmorphic
 * black/gold, with a subtle hover-expand to ~360×240. Sectors render as squares,
 * agents as colored dots (color by status, brightness by activity), and the live
 * camera viewport as a gold rectangle. Clicking the minimap pans the main camera
 * to that world point (via window.cinematicCamera, a provided onNavigate, or a
 * `minimap-navigate` CustomEvent). Respects prefers-reduced-motion.
 *
 * It is a pure VIEW — it pulls everything through an injected `source`, so it has
 * no PIXI / engine dependency and tests against a mock source.
 *
 * ── Mount one-liner (from agency-world-viz or any host that owns the engine —
 *    do NOT edit this file to wire it; wire from the host):
 *
 *    import "../components/world-minimap";              // registers the element
 *    const mm = document.createElement("world-minimap") as WorldMinimap;
 *    mm.source = {
 *      worldBounds: () => this.eng()?.getWorldBounds?.() ?? null,
 *      sectors:     () => this.eng()?.getSectorRects?.() ?? [],
 *      agents:      () => this.eng()?.getAgentDots?.() ?? [],
 *      camera:      () => this.eng()?.getCameraRect?.() ?? null,   // world-space {x,y,width,height} (center+size)
 *      flyTo:       (x, y) => this.eng()?.cameraFlyTo?.(x, y, 1.2, 700),
 *    };
 *    this.renderRoot.appendChild(mm);
 *    // …and on teardown: mm.remove();
 */

// ── Public source contract ────────────────────────────────────────────────────

export interface MinimapWorldBounds {
  minX: number;
  minY: number;
  maxX: number;
  maxY: number;
}

export interface MinimapSector {
  id: string;
  x: number;
  y: number;
  /** Half-extent in world px (square). Default 60. */
  w?: number;
  h?: number;
  color?: string;
}

export interface MinimapAgent {
  id: string;
  x: number;
  y: number;
  /** "active" | "working" | "idle" | "error" | "alert" | string */
  status?: string;
  /** 0..1 — drives dot brightness. Default 0.6. */
  activity?: number;
}

/** Camera viewport rect in WORLD coordinates: center (x,y) + size (width,height). */
export interface MinimapCameraRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface MinimapSource {
  worldBounds(): MinimapWorldBounds | null;
  sectors(): MinimapSector[];
  agents(): MinimapAgent[];
  camera(): MinimapCameraRect | null;
  /** Optional direct nav; if absent we use window.cinematicCamera / the event. */
  flyTo?(x: number, y: number): void;
}

const COMPACT = { w: 180, h: 120 };
const EXPANDED = { w: 360, h: 240 };
const PADDING = 8; // inner padding (device-independent px) around the schematic

const GOLD = "#e8c060";
const GOLD_DIM = "rgba(232,192,96,0.35)";

const STATUS_COLORS: Record<string, string> = {
  active: "#6ee7a8",
  working: GOLD,
  busy: GOLD,
  idle: "#7a8290",
  error: "#f0676b",
  alert: "#f59e42",
  offline: "#4a5160",
};

export class WorldMinimap extends HTMLElement {
  private _source: MinimapSource | null = null;
  private canvas!: HTMLCanvasElement;
  private ctx!: CanvasRenderingContext2D | null;
  private rafId: number | null = null;
  private expanded = false;
  private mounted = false;
  private dpr = 1;

  // ── Public API ───────────────────────────────────────────────────────────────

  set source(s: MinimapSource | null) {
    this._source = s;
    if (this.mounted) this.draw();
  }
  get source(): MinimapSource | null {
    return this._source;
  }

  /** Optional callback alternative to flyTo/window — receives world coords on click. */
  onNavigate: ((x: number, y: number) => void) | null = null;

  // ── Lifecycle ────────────────────────────────────────────────────────────────

  connectedCallback(): void {
    if (this.mounted) return;
    this.mounted = true;
    this.attachShadow({ mode: "open" });
    this.dpr = Math.min(2, window.devicePixelRatio || 1);
    this.buildDom();
    this.resizeCanvas();
    this.startLoop();
  }

  disconnectedCallback(): void {
    this.mounted = false;
    this.stopLoop();
  }

  // ── DOM / styling ──────────────────────────────────────────────────────────────

  private buildDom(): void {
    const root = this.shadowRoot!;
    const style = document.createElement("style");
    style.textContent = `
      :host {
        position: fixed;
        right: 16px;
        bottom: 16px;
        z-index: 60;
        --mm-w: ${COMPACT.w}px;
        --mm-h: ${COMPACT.h}px;
      }
      .frame {
        width: var(--mm-w);
        height: var(--mm-h);
        border-radius: 12px;
        padding: 6px;
        box-sizing: border-box;
        background: linear-gradient(160deg, rgba(10,12,18,0.82), rgba(6,7,12,0.92));
        border: 1px solid ${GOLD_DIM};
        box-shadow: 0 8px 30px rgba(0,0,0,0.55), inset 0 0 24px rgba(232,192,96,0.05);
        backdrop-filter: blur(10px) saturate(1.1);
        -webkit-backdrop-filter: blur(10px) saturate(1.1);
        transition: width .28s cubic-bezier(.2,.8,.2,1), height .28s cubic-bezier(.2,.8,.2,1), box-shadow .28s;
        cursor: crosshair;
        position: relative;
        overflow: hidden;
      }
      :host(:hover) {
        --mm-w: ${EXPANDED.w}px;
        --mm-h: ${EXPANDED.h}px;
      }
      :host(:hover) .frame {
        box-shadow: 0 12px 44px rgba(0,0,0,0.6), 0 0 0 1px ${GOLD_DIM}, inset 0 0 30px rgba(232,192,96,0.08);
      }
      canvas { display:block; width:100%; height:100%; border-radius:8px; }
      .label {
        position:absolute; top:7px; left:10px;
        font: 600 9px/1 ui-monospace, SFMono-Regular, Menlo, monospace;
        letter-spacing: .14em; text-transform: uppercase;
        color: ${GOLD}; opacity:.55; pointer-events:none; user-select:none;
        text-shadow: 0 1px 3px rgba(0,0,0,.7);
      }
      @media (prefers-reduced-motion: reduce) {
        .frame { transition: none; }
      }
    `;
    const frame = document.createElement("div");
    frame.className = "frame";
    const canvas = document.createElement("canvas");
    const label = document.createElement("div");
    label.className = "label";
    label.textContent = "RADAR";

    frame.appendChild(canvas);
    frame.appendChild(label);
    root.appendChild(style);
    root.appendChild(frame);

    this.canvas = canvas;
    this.ctx = canvas.getContext("2d");

    canvas.addEventListener("click", (e) => this.handleClick(e));
    // Hover-expand changes CSS size → resize the backing store next frame.
    this.addEventListener("mouseenter", () => { this.expanded = true; this.deferResize(); });
    this.addEventListener("mouseleave", () => { this.expanded = false; this.deferResize(); });
  }

  private deferResize(): void {
    // CSS transition changes the box; resize backing store after it settles.
    setTimeout(() => { this.resizeCanvas(); this.draw(); }, 300);
    // Also resize immediately so the schematic isn't blank mid-transition.
    requestAnimationFrame(() => { this.resizeCanvas(); this.draw(); });
  }

  private resizeCanvas(): void {
    if (!this.canvas) return;
    const rect = this.canvas.getBoundingClientRect();
    const w = Math.max(1, Math.round((rect.width || COMPACT.w) * this.dpr));
    const h = Math.max(1, Math.round((rect.height || COMPACT.h) * this.dpr));
    if (this.canvas.width !== w) this.canvas.width = w;
    if (this.canvas.height !== h) this.canvas.height = h;
  }

  // ── Render loop ────────────────────────────────────────────────────────────────

  private startLoop(): void {
    if (this.reducedMotion()) {
      // No continuous rAF — draw once and on source/hover changes only.
      this.draw();
      return;
    }
    if (this.rafId != null) return;
    const loop = () => {
      this.rafId = requestAnimationFrame(loop);
      this.draw();
    };
    this.rafId = requestAnimationFrame(loop);
  }

  private stopLoop(): void {
    if (this.rafId != null) { cancelAnimationFrame(this.rafId); this.rafId = null; }
  }

  // ── Projection (world ↔ minimap) ─────────────────────────────────────────────

  private bounds(): MinimapWorldBounds {
    const b = this._source?.worldBounds?.() ?? null;
    if (b && b.maxX > b.minX && b.maxY > b.minY) return b;
    // Fallback: derive from agents/sectors so we never divide by zero.
    const pts = [
      ...(this.safe(() => this._source?.agents?.()) ?? []),
      ...(this.safe(() => this._source?.sectors?.()) ?? []),
    ];
    if (!pts.length) return { minX: 0, minY: 0, maxX: 1600, maxY: 1200 };
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const p of pts) {
      minX = Math.min(minX, p.x); maxX = Math.max(maxX, p.x);
      minY = Math.min(minY, p.y); maxY = Math.max(maxY, p.y);
    }
    const padX = (maxX - minX || 400) * 0.15;
    const padY = (maxY - minY || 400) * 0.15;
    return { minX: minX - padX, minY: minY - padY, maxX: maxX + padX, maxY: maxY + padY };
  }

  /** World → canvas (device px), letterboxed to preserve aspect. */
  private proj(b: MinimapWorldBounds): {
    sx: number; sy: number; ox: number; oy: number;
  } {
    const cw = this.canvas.width;
    const ch = this.canvas.height;
    const pad = PADDING * this.dpr;
    const availW = cw - pad * 2;
    const availH = ch - pad * 2;
    const wW = b.maxX - b.minX;
    const wH = b.maxY - b.minY;
    const s = Math.min(availW / wW, availH / wH);
    // Center the letterboxed schematic.
    const ox = pad + (availW - wW * s) / 2;
    const oy = pad + (availH - wH * s) / 2;
    return { sx: s, sy: s, ox, oy };
  }

  private toCanvas(
    x: number, y: number, b: MinimapWorldBounds, p: ReturnType<WorldMinimap["proj"]>,
  ): { cx: number; cy: number } {
    return { cx: p.ox + (x - b.minX) * p.sx, cy: p.oy + (y - b.minY) * p.sy };
  }

  // ── Draw ─────────────────────────────────────────────────────────────────────

  private draw(): void {
    const ctx = this.ctx;
    if (!ctx || !this.canvas) return;
    const cw = this.canvas.width;
    const ch = this.canvas.height;
    ctx.clearRect(0, 0, cw, ch);

    // Backdrop grid for the "radar" feel.
    ctx.fillStyle = "rgba(8,10,16,0.6)";
    ctx.fillRect(0, 0, cw, ch);
    this.drawGrid(ctx, cw, ch);

    const b = this.bounds();
    const p = this.proj(b);

    // Sectors as faint gold squares.
    for (const sec of this.safe(() => this._source?.sectors?.()) ?? []) {
      const { cx, cy } = this.toCanvas(sec.x, sec.y, b, p);
      const halfW = (sec.w ?? 60) * p.sx;
      const halfH = (sec.h ?? sec.w ?? 60) * p.sy;
      ctx.fillStyle = sec.color ?? "rgba(232,192,96,0.10)";
      ctx.strokeStyle = "rgba(232,192,96,0.22)";
      ctx.lineWidth = 1 * this.dpr;
      ctx.fillRect(cx - halfW, cy - halfH, halfW * 2, halfH * 2);
      ctx.strokeRect(cx - halfW, cy - halfH, halfW * 2, halfH * 2);
    }

    // Agents as colored dots — color by status, brightness/size by activity.
    for (const a of this.safe(() => this._source?.agents?.()) ?? []) {
      const { cx, cy } = this.toCanvas(a.x, a.y, b, p);
      const act = Math.max(0, Math.min(1, a.activity ?? 0.6));
      const color = STATUS_COLORS[a.status ?? "idle"] ?? STATUS_COLORS.idle;
      const r = (this.expanded ? 3 : 2) * this.dpr * (0.7 + act * 0.6);
      ctx.globalAlpha = 0.45 + act * 0.55;
      // Glow.
      ctx.shadowColor = color;
      ctx.shadowBlur = (this.expanded ? 8 : 4) * act * this.dpr;
      ctx.fillStyle = color;
      ctx.beginPath();
      ctx.arc(cx, cy, r, 0, Math.PI * 2);
      ctx.fill();
      ctx.shadowBlur = 0;
      ctx.globalAlpha = 1;
    }

    // Camera viewport rectangle.
    const cam = this.safe(() => this._source?.camera?.());
    if (cam) {
      const tl = this.toCanvas(cam.x - cam.width / 2, cam.y - cam.height / 2, b, p);
      const w = cam.width * p.sx;
      const h = cam.height * p.sy;
      ctx.strokeStyle = GOLD;
      ctx.lineWidth = 1.4 * this.dpr;
      ctx.shadowColor = GOLD;
      ctx.shadowBlur = 6 * this.dpr;
      ctx.strokeRect(tl.cx, tl.cy, w, h);
      ctx.shadowBlur = 0;
      ctx.fillStyle = "rgba(232,192,96,0.06)";
      ctx.fillRect(tl.cx, tl.cy, w, h);
    }
  }

  private drawGrid(ctx: CanvasRenderingContext2D, cw: number, ch: number): void {
    ctx.strokeStyle = "rgba(232,192,96,0.06)";
    ctx.lineWidth = 1;
    const step = 24 * this.dpr;
    for (let x = 0; x <= cw; x += step) {
      ctx.beginPath(); ctx.moveTo(x, 0); ctx.lineTo(x, ch); ctx.stroke();
    }
    for (let y = 0; y <= ch; y += step) {
      ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(cw, y); ctx.stroke();
    }
  }

  // ── Interaction ────────────────────────────────────────────────────────────────

  private handleClick(e: MouseEvent): void {
    const b = this.bounds();
    const p = this.proj(b);
    const rect = this.canvas.getBoundingClientRect();
    // Pointer (CSS px) → canvas device px → world.
    const cx = (e.clientX - rect.left) * (this.canvas.width / rect.width);
    const cy = (e.clientY - rect.top) * (this.canvas.height / rect.height);
    const wx = b.minX + (cx - p.ox) / p.sx;
    const wy = b.minY + (cy - p.oy) / p.sy;

    // Prefer explicit nav hooks, then global cinematic camera, then an event.
    if (this.onNavigate) { this.onNavigate(wx, wy); return; }
    if (this._source?.flyTo) { this._source.flyTo(wx, wy); return; }
    try {
      const cc = window.cinematicCamera;
      if (cc && typeof (cc as { panTo?: unknown }).panTo === "function") {
        (cc as unknown as { panTo: (x: number, y: number) => void }).panTo(wx, wy);
        return;
      }
    } catch { /* ignore */ }
    this.dispatchEvent(new CustomEvent("minimap-navigate", {
      detail: { x: wx, y: wy }, bubbles: true, composed: true,
    }));
  }

  // ── utils ──────────────────────────────────────────────────────────────────────

  private safe<T>(fn: () => T): T | undefined {
    try { return fn(); } catch { return undefined; }
  }

  private reducedMotion(): boolean {
    try { return !!window.matchMedia?.("(prefers-reduced-motion: reduce)").matches; }
    catch { return false; }
  }
}

if (typeof customElements !== "undefined" && !customElements.get("world-minimap")) {
  customElements.define("world-minimap", WorldMinimap);
}

declare global {
  interface HTMLElementTagNameMap {
    "world-minimap": WorldMinimap;
  }
}
