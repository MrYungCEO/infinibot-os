// Generate the plugin-rooms harness fixture from the real first-party
// manifests, in the shape plugins.list returns (contributes + appearance +
// rosterAgentIds). Run: node ui/src/dev/gen-plugin-rooms-fixture.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const IDS = ["infinicode", "robovoice", "omniclinic", "flypic", "infinitrade", "solatrix", "discipline", "content-studio", "products", "canvas-library", "business-agency", "mcp-excalidraw"];

const out = [];
for (const dir of IDS) {
  const m = JSON.parse(readFileSync(join(root, "extensions", dir, "infinibot.plugin.json"), "utf8"));
  const c = m.contributes ?? {};
  const rosterAgentIds = [];
  for (const rel of c.agents ?? []) {
    const f = join(root, "extensions", dir, rel);
    if (!existsSync(f)) continue;
    const r = JSON.parse(readFileSync(f, "utf8"));
    for (const a of r.agents ?? []) if (a?.id) rosterAgentIds.push(a.id);
  }
  out.push({
    id: m.id,
    name: m.name,
    manifestVersion: 2,
    status: "loaded",
    enabled: true,
    contributes: {
      nav: c.nav ?? [],
      pages: c.pages ?? [],
      rpc: (c.rpc ?? []).map((r) => ({ method: r.method, scope: r.scope, ...(r.aliases ? { aliases: r.aliases } : {}) })),
      rpcAliases: (c.rpcAliases ?? []).map((a) => ({ method: a.method, target: a.target, scope: a.scope })),
      http: c.http ?? [],
      tools: (c.tools ?? []).map((t) => (typeof t === "string" ? t : t.name)),
      agents: c.agents ?? [],
      ...(c.navSection ? { navSection: c.navSection } : {}),
      ...(c.mapRoom ? { mapRoom: c.mapRoom } : {}),
    },
    rosterAgentIds,
    appearance: { icon: m.appearance?.icon, monogram: m.appearance?.monogram, customized: false, themes: { dark: { vars: {} }, light: { vars: {} } } },
  });
}
const target = join(here, "plugin-rooms-fixture.ts");
writeFileSync(target, `// GENERATED by gen-plugin-rooms-fixture.mjs from extensions/*/infinibot.plugin.json — do not edit.\n// plugins.list-shaped items for the mesh-plugin-rooms harness.\nexport const PLUGIN_ROOMS_FIXTURE = ${JSON.stringify(out, null, 2)} as const;\n`);
console.log(`wrote ${target}: ${out.length} plugins`);
