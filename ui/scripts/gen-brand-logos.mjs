#!/usr/bin/env node
/**
 * Regenerates ui/src/ui/lib/provider-logos.data.ts from the upstream SVGs.
 *
 *   npm pack @lobehub/icons-static-svg   (extract to <lobe>, MIT)
 *   node ui/scripts/gen-brand-logos.mjs <lobe>/package/icons <kv-repo>/public/kv-bulb.svg <svgo-bin>
 *
 * Marks are used as supplied: no recolouring, no redrawing. See
 * docs/licensing/BRAND-USAGE.md before adding one.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [lobeDir, kvBulb, svgo] = process.argv.slice(2);
if (!lobeDir || !kvBulb || !svgo) {
  console.error("usage: gen-brand-logos.mjs <lobe-icons-dir> <kv-bulb.svg> <svgo-bin>");
  process.exit(1);
}

// id → upstream file. "mono" marks are black/white-only brands: they follow the
// theme's strongest text colour. "color" marks keep their official colours.
const LOGOS = {
  claude: ["claude-color", "color"],
  openai: ["openai", "mono"],
  codex: ["codex-color", "color"],
  gemini: ["gemini-color", "color"],
  grok: ["grok", "mono"],
  opencode: ["opencode", "mono"],
  openrouter: ["openrouter", "mono"],
  ollama: ["ollama", "mono"],
  deepseek: ["deepseek-color", "color"],
  mistral: ["mistral-color", "color"],
  groq: ["groq", "mono"],
  kimi: ["kimi-color", "color"],
  qwen: ["qwen-color", "color"],
  together: ["together-color", "color"],
  cohere: ["cohere-color", "color"],
  perplexity: ["perplexity-color", "color"],
  fireworks: ["fireworks-color", "color"],
  cerebras: ["cerebras-color", "color"],
  zai: ["zai", "mono"],
  llamaindex: ["llamaindex", "mono"],
  replicate: ["replicate", "mono"],
  huggingface: ["huggingface-color", "color"],
  vllm: ["vllm-color", "color"],
};

function parts(src) {
  const viewBox = /viewBox="([^"]+)"/.exec(src)?.[1];
  const evenodd = /<svg[^>]*fill-rule="evenodd"/.test(src);
  const body = src.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/<title>.*?<\/title>/, "");
  if (!viewBox || !body || /[`$]/.test(body)) throw new Error("unexpected svg");
  return { viewBox, body: evenodd ? `<g fill-rule="evenodd">${body}</g>` : body };
}

// The KV bulb ships as a dark class-styled fill; svgo folds the transforms and we
// strip the fill so the tile can show it in KV gold.
const tmp = join(mkdtempSync(join(tmpdir(), "kv-bulb-")), "kv.svg");
execFileSync(svgo, ["--multipass", "-i", kvBulb, "-o", tmp], { stdio: "ignore" });
const kv = parts(readFileSync(tmp, "utf8").replace(/<defs>.*?<\/defs>/, "").replace(/ class="[^"]*"/g, "").replace(/ id="[^"]*"/g, "").replace(/ data-name="[^"]*"/g, ""));

const rows = Object.entries(LOGOS).map(([id, [file, kind]]) => {
  const { viewBox, body } = parts(readFileSync(join(lobeDir, `${file}.svg`), "utf8"));
  return `  ${JSON.stringify(id)}: { kind: "${kind}", viewBox: "${viewBox}", body: svg\`${body}\` },`;
});
rows.push(`  kv: { kind: "kv", viewBox: "${kv.viewBox}", body: svg\`${kv.body}\` },`);

const out = `// GENERATED by ui/scripts/gen-brand-logos.mjs. Do not edit by hand.
//
// Sources and licences:
//   - Third-party marks: @lobehub/icons-static-svg 1.101.0 (MIT, github.com/lobehub/lobe-icons).
//     The MIT licence covers the SVG files only. Every mark stays a trademark of its
//     owner; see docs/licensing/BRAND-USAGE.md and TRADEMARKS.md.
//   - kv: KinglyVault's own brand bulb (KinglyVault repo, public/kv-bulb.svg).
import { svg, type SVGTemplateResult } from "lit";

export type ProviderLogoMark = { kind: "color" | "mono" | "kv"; viewBox: string; body: SVGTemplateResult };

export const PROVIDER_LOGO_MARKS = {
${rows.join("\n")}
} satisfies Record<string, ProviderLogoMark>;
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "../src/ui/lib/provider-logos.data.ts"), out);
