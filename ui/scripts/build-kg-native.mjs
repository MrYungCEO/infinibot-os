#!/usr/bin/env node
/**
 * Bundle the shared knowledge-graph code for the native mobile app.
 *
 *   node ui/scripts/build-kg-native.mjs           # write mobile/src/kg/generated/*
 *   node ui/scripts/build-kg-native.mjs --check   # exit 1 when the committed bundles are stale
 *
 * The mobile app (Expo / Metro) can't import ui/src directly without a Metro
 * config change and a dev-server restart, so the pure pipeline
 * (knowledge-graph-scene + model/ops/links/layout/consolidate) and the 3D
 * stage (glow3d + three, three kept external) are bundled into two ESM files
 * the app imports. The mobile test suite runs `--check` so a source change
 * without a rebuild fails CI (see mobile/src/__tests__/kg-native-bundle.test.js).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = dirname(fileURLToPath(import.meta.url));
const uiRoot = resolve(here, "..");
const outDir = resolve(uiRoot, "../mobile/src/kg/generated");
const require = createRequire(import.meta.url);
const esbuild = require("esbuild");

const navShim = join(here, "kg-native", "navigation-shim.ts");
const shimPlugin = {
  name: "kg-native-shims",
  setup(build) {
    // The web navigation module drags in the whole shell — swap in a stub.
    build.onResolve({ filter: /^\.\.\/navigation$/ }, () => ({ path: navShim }));
  },
};

const BANNER = (name) =>
  `/* eslint-disable */\n// GENERATED by ui/scripts/build-kg-native.mjs from ui/src — do not edit.\n// ${name}: shared with the web knowledge graph (see the script header).\n`;

async function bundle(entry, name, external) {
  const res = await esbuild.build({
    entryPoints: [join(here, "kg-native", entry)],
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2019",
    write: false,
    external,
    plugins: [shimPlugin],
    legalComments: "none",
    charset: "utf8",
    logLevel: "silent",
    absWorkingDir: uiRoot,
    banner: { js: BANNER(name) },
  });
  return res.outputFiles[0].text;
}

const outputs = {
  "kg-core.js": await bundle("core-entry.ts", "kg-core", []),
  "kg-stage.js": await bundle("stage-entry.ts", "kg-stage", ["three", "three/*"]),
};

const check = process.argv.includes("--check");
let stale = 0;
for (const [file, text] of Object.entries(outputs)) {
  const path = join(outDir, file);
  if (check) {
    let cur = "";
    try {
      cur = readFileSync(path, "utf8");
    } catch {
      /* missing */
    }
    if (cur !== text) {
      stale++;
      console.error(`stale: mobile/src/kg/generated/${file} — run node ui/scripts/build-kg-native.mjs`);
    }
  } else {
    mkdirSync(outDir, { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote mobile/src/kg/generated/${file} (${(text.length / 1024).toFixed(0)} KB)`);
  }
}
process.exit(stale ? 1 : 0);
