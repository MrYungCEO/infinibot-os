#!/usr/bin/env node
/**
 * Bundle the 3D Agent Mesh world for the native mobile app.
 *
 *   node ui/scripts/build-mesh3d-native.mjs           # write mobile/src/lib/mesh/generated/mesh3d.js
 *   node ui/scripts/build-mesh3d-native.mjs --check   # exit 1 when the committed bundle is stale
 *
 * Same approach as build-kg-native.mjs: the app can't import ui/src, so the
 * shared MeshWorldModel (the one adapter behind the web 2D and 3D views) and
 * MeshWorldScene are bundled into one ESM file, three kept external. The
 * mobile suite runs `--check` (mobile/src/__tests__/mesh3d-native-bundle.test.js).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = dirname(fileURLToPath(import.meta.url));
const uiRoot = resolve(here, "..");
const outFile = resolve(uiRoot, "../mobile/src/lib/mesh/generated/mesh3d.js");
const require = createRequire(import.meta.url);
const esbuild = require("esbuild");

const res = await esbuild.build({
  entryPoints: [join(here, "mesh3d-native", "entry.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2019",
  write: false,
  external: ["three", "three/*"],
  legalComments: "none",
  charset: "utf8",
  logLevel: "silent",
  absWorkingDir: uiRoot,
  banner: {
    js: "/* eslint-disable */\n// GENERATED by ui/scripts/build-mesh3d-native.mjs from ui/src — do not edit.\n// mesh3d: the web Agent Mesh 3D world (model + scene), shared with <mesh-world-3d>.\n",
  },
});
const text = res.outputFiles[0].text;

if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(outFile, "utf8");
  } catch {
    /* missing */
  }
  if (cur !== text) {
    console.error("stale: mobile/src/lib/mesh/generated/mesh3d.js — run node ui/scripts/build-mesh3d-native.mjs");
    process.exit(1);
  }
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, text);
  console.log(`wrote mobile/src/lib/mesh/generated/mesh3d.js (${(text.length / 1024).toFixed(0)} KB)`);
}
